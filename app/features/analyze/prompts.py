from typing import Any, Dict, List, Optional

from app.shared.legal_reality_system import with_legal_doctrine
from app.shared.legal_engine.schemas import LegalRunContext
from app.shared.legal_engine.stage3.prompt_block import format_legal_run_context_for_prompt


def build_analysis_prompt(
    facts: Dict[str, Any],
    verified_rag: List[Dict],
    *,
    legal_run_context: Optional[LegalRunContext] = None,
) -> str:
    """
    Промпт юридического разбора документа (РК).
    RAG обязателен; в ответе — жёсткая структура, короткий практический стиль.
    """

    facts_block = f"""
ТИП ДОКУМЕНТА:
{facts.get("document_type")}

ТЕКСТ ДОКУМЕНТА:
{facts.get("document_text")}

ЦЕЛЬ АНАЛИЗА:
{facts.get("goals")}

КОНТЕКСТ:
{facts.get("context") or "не указан"}
""".strip()

    if legal_run_context is not None:
        facts_block = facts_block + "\n\n" + format_legal_run_context_for_prompt(legal_run_context)

    rag_blocks: List[str] = []
    for art in verified_rag:
        if not isinstance(art, dict):
            continue
        articles = art.get("articles")
        if not isinstance(articles, list) or not articles:
            continue
        first = articles[0]
        if not isinstance(first, dict):
            continue
        article_num = first.get("article")
        article_text = first.get("text")
        if article_num is None or article_text is None:
            continue
        if not str(article_text).strip():
            continue
        source = art.get("source", "—")
        rag_blocks.append(f"[{source}, статья {article_num}]\n{article_text}")

    if not rag_blocks:
        raise RuntimeError("RAG parsed, but no valid legal articles found")

    rag_text = "\n\n".join(rag_blocks)

    rag_sources_catalog = """
Технические id корпуса (для справки; в ответе пользователю не копируй список целиком, не подменяй им названия актов):
kz_gk_code, kz_pk_code, kz_nk_code, kz_tm_code, kz_koap_code, kz_appc_code, kz_tk_code,
kz_vs_np_* , kz_law_* (см. фрагменты ниже — там человекочитаемые названия источников).
""".strip()

    system = """
Ты — юрист-практик по праву Республики Казахстан. Делаешь разбор УЖЕ СУЩЕСТВУЮЩЕГО документа для клиента.

НЕ делаешь: общую лекцию, переписывание договора целиком, новый договор, заявление, претензию, «консультацию в отрыве от текста».

ОПОРА НА НОРМЫ:
- Цитируй и опирайся только на фрагменты из блока «НОРМЫ ПРАВА» ниже.
- Не придумывай номера статей и названия актов, которых нет в этом блоке.
- В разделе «Применённые нормы» перечисляй ТОЛЬКО то, что реально опирал на текст договора/документа и что есть в фрагментах RAG (источник + статья как в префиксе [источник, статья N]).
- Не заполняй список «для объёма»: не добавляй общегражданские институты (вещное право, виды собственности, клад, абстрактная долевая собственность и т.п.), если они не следуют из конкретных условий текста.
- Ориентир: не больше 8–10 маркеров, только по теме сделки или спора из документа.
- Договор поставки/купли-продажи без импорта, таможни, ЕАЭС и ВЭД в тексте: ядро — ГК РК (обязательства, поставка, расчёты, ответственность, расторжение, недостатки); не уводи «Применённые нормы» в НК/таможенный кодекс и узкоспециальные импортные статьи, если они не следуют из условий документа. Если в тексте явно есть импорт/таможня/ЕАЭС/инвойс как предмет — тогда налоговые и таможенные нормы уместны.

СТИЛЬ (жёстко):
- Деловой, короткий, без пафоса, без академических обобщений и без «глубокого научного анализа».
- Не повторяй один смысл разными абзацами; не пиши синонимами то же самое в следующем абзаце.
- Запрещены лексика уровня «представляется целесообразным отметить», «следует подчеркнуть фундаментальное значение».
- Конкретика: к пункту документа / условию — что не так, риск, правка.
- Объём всего ответа: целиться в 600–1200 слов; длиннее — только если документ объективно сложный, но без воды.
- ФИНАЛ: последние символы ответа должны быть внутри раздела «Практический вывод». После него — НИ ОДНОЙ строки (ни резюме, ни «таким образом», ни P.S.).
""".strip()

    output_spec = """
ФОРМАТ ОТВЕТА (СТРОГО эти заголовки Markdown, в таком порядке, без других верхнеуровневых разделов):

### Общая оценка
3–5 коротких строк: что за документ по сути, стороны/сделка (если видно из текста), общий уровень риска (низкий/средний/высокый) — одной фразой обоснуй.

### Ключевые риски
5–10 пронумерованных пунктов. В КАЖДОМ пункте ТОЛЬКО три подстрочки (без подпунктов глубже):
- **Что не так:** …
- **Риск:** …
- **Что исправить:** …
Не дублируй один риск в нескольких пунктах.

### Что уже хорошо
2–5 коротких маркеров («— …»). Только реально полезные плюсы; если нечего сказать — одна строка: «Явных сильных сторон по тексту не выделяется».

### Применённые нормы
Только маркеры «— …», одна норма = одна строка, без развёрнутых цитат и без подпунктов. Не более 10 строк.
Формат строки: «— [источник, статья N] + до 8 слов: зачем использовал».
Только нормы из блока RAG по сути договора; не дублируй близкие статьи одной идеей. Если фрагмента не хватило — одна честная строка без выдуманной статьи.

### Практический вывод
Ровно 3–6 коротких строк (не абзацы на полстраницы), суммарно примерно до 650 символов: подпись как есть / после правок / не подписывать; первый практический шаг.
После последней строки этого раздела ответ ЗАКАНЧИВАЕТСЯ — не добавляй заключений, итогов, списков и новых заголовков.
""".strip()

    hard_rules = """
ЗАПРЕЩЕНО:
- Любой текст после раздела «Практический вывод», включая «Таким образом», «Кроме того», «Особое внимание…», повторные рекомендации, второе заключение.
- Второй проход по тем же рискам другими словами.
- Абзацы «в целом законодательство РК…» без привязки к конкретному условию в документе.
- Выдуманные статьи и «судебная практика» с выдуманными реквизитами.
- Мета-текст и дисклеймеры на полэкрана.

РАЗРЕШЕНО:
- Указать пробел в документе и пробел в RAG отдельно.
- Коротко обозначить, когда нужен очный юрист/бухгалтер, если это следует из цели анализа.
""".strip()

    return with_legal_doctrine(
        f"""
{system}

====================
ФАКТИЧЕСКИЕ ДАННЫЕ
====================
{facts_block}

====================
СПРАВОЧНО: КОРПУС RAG
====================
{rag_sources_catalog}

====================
НОРМЫ ПРАВА (РК) — ФРАГМЕНТЫ ДЛЯ ОПОРЫ
====================
{rag_text}

====================
ФОРМАТ ИТОГОВОГО ОТВЕТА
====================
{output_spec}

====================
ОГРАНИЧЕНИЯ
====================
{hard_rules}

Сформируй ответ строго по структуре выше: ровно пять разделов с подзаголовками ### в указанном порядке, без шестого раздела и без приложений.
Не включай полный текст анализируемого договора повторно. После «Практический вывод» — стоп.
""".strip()
    )

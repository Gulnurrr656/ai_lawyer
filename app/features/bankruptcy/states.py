from aiogram.fsm.state import StatesGroup, State


# =========================
# BANKRUPTCY FSM (КАНОН)
# РОЛЬ: ОЦЕНКА И СТРАТЕГИЯ БАНКРОТСТВА
# =========================

class BankruptcyStates(StatesGroup):
    # 1️⃣ Субъект банкротства
    # (ФЛ / ИП / ТОО)
    subject = State()

    # 2️⃣ Общая информация о долгах
    # (сумма, характер, давность)
    debts = State()

    # 3️⃣ Кредиторы
    # (банк / налоговая / контрагенты / несколько)
    creditors = State()

    # 4️⃣ Контекст и риски
    # (давление, угрозы, номинал, спорные сделки)
    risks = State()

    # 5️⃣ Дополнительные детали
    # (исполнительные производства, суды, аресты — если есть)
    additional_info = State()

    # 6️⃣ Подтверждение
    confirm = State()
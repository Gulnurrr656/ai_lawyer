from typing import Dict, List

from app.shared.legal_reality_system import with_legal_doctrine


def build_claim_prompt(
    facts: Dict,
    verified_rag: List[Dict],
) -> str:
    """
    ФИНАЛЬНЫЙ КАНОНИЧЕСКИЙ PROMPT ПРЕТЕНЗИИ / ЖАЛОБЫ.
    Архитектура = контракт.
    Роль = CLAIMS (досудебная / административная).
    """

    # =================================================
    # 1️⃣ FACTS
    # =================================================
    facts_block = f"""
ТИП ДОКУМЕНТА:
{facts.get("claim_type") or "Не согласовано"}

ЗАЯВИТЕЛЬ:
{facts.get("applicant") or "Не согласовано"}

АДРЕСАТ:
{facts.get("respondent") or "Не согласовано"}

ОТНОШЕНИЯ СТОРОН:
{facts.get("relationship") or "Не согласовано"}

СУТЬ НАРУШЕНИЯ:
{facts.get("violation") or "Не согласовано"}

ТРЕБОВАНИЯ ЗАЯВИТЕЛЯ:
{facts.get("demands") or "Не согласовано"}
""".strip()

    if facts.get("attachments"):
        facts_block += f"""

ДОКАЗАТЕЛЬСТВА / ПРИЛОЖЕНИЯ:
{facts.get("attachments")}
"""

    # =================================================
    # 2️⃣ RAG — НОРМЫ ПРАВА (СТРОГО, БЕЗ ОТКАЗОВ)
    # =================================================
    rag_blocks: List[str] = []

    for art in verified_rag or []:
        if not isinstance(art, dict):
            continue

        articles = art.get("articles")
        if not isinstance(articles, list) or not articles:
            continue

        first = articles[0]
        if not isinstance(first, dict):
            continue

        article_num = first.get("article")
        article_text = first.get("text")

        if not article_num or not article_text:
            continue

        source = art.get("source", "—")

        rag_blocks.append(
            f"[{source}, статья {article_num}]\n{article_text}"
        )

    if not rag_blocks:
        rag_blocks.append(
            "Нормы права применяются в пределах переданных источников. "
            "Отсутствие конкретной статьи фиксируется как неполнота данных, "
            "а не как основание для отказа."
        )

    rag_text = "\n\n".join(rag_blocks)

    # =================================================
    # 3️⃣ КАТАЛОГ RAG (ФИКСИРОВАННЫЙ)
    # =================================================
    rag_sources_catalog = """
📚 КОДЕКСЫ
kz_gk_code
kz_pk_code
kz_nk_code
kz_tm_code
kz_koap_code
kz_appc_code
kz_tk_code

⚖️ НОРМАТИВНЫЕ ПОСТАНОВЛЕНИЯ ВС
kz_vs_np_civil_judgment_code
kz_vs_np_civil_procedure_norms_code
kz_vs_np_invalidity_of_transactions_code
kz_vs_np_llp_and_alp_code

📜 ЗАКОНЫ
kz_law_buh_code
kz_law_currency_control_code
kz_law_state_registration_code
kz_law_personal_data_code
kz_law_llp_code
kz_law_arbitration_code
""".strip()

    # =================================================
    # 4️⃣ SYSTEM ROLE — 🔒 РОЛЬ CLAIMS
    # =================================================
    system = """
ТЫ — ЮРИСТ РЕСПУБЛИКИ КАЗАХСТАН С ОПЫТОМ 30+ ЛЕТ.

ТЫ НЕ КОНСУЛЬТАНТ.
ТЫ НЕ АНАЛИТИК.
ТЫ НЕ ПИШЕШЬ РЕКОМЕНДАЦИИ.

ТВОЯ ЕДИНСТВЕННАЯ РОЛЬ:
➡️ СОСТАВЛЕНИЕ ПРЕТЕНЗИИ ИЛИ ЖАЛОБЫ
(досудебной или административной).

ЖАНР (КРИТИЧЕСКИ ВАЖНО):
- Формальный юридический документ.
- Фиксация нарушения в пределах представленных фактов.
- Формулирование требований в допустимой процессуальной форме.

ДОПУСТИМО:
- фиксировать «не согласовано»
- фиксировать «не указано»
- фиксировать неполноту данных

ЗАПРЕЩЕНО:
- консультационный стиль
- анализ рисков
- советы и варианты
- уголовные формулировки

ОБЯЗАТЕЛЬНО:
- Используй ТОЛЬКО нормы из переданного RAG
- Если норма отсутствует — зафиксируй это корректно
- Пиши как документ, а не объяснение
"""

    # =================================================
    # 5️⃣ СТРУКТУРА ПРЕТЕНЗИИ / ЖАЛОБЫ
    # =================================================
    structure = """
СТРУКТУРА ДОКУМЕНТА:

1. Сведения о заявителе
2. Сведения об адресате
3. Описание правоотношений сторон
4. Фактические обстоятельства и нарушение
5. Правовая оценка (Правовое основание)
6. Требования заявителя
7. Срок для ответа / исполнения
8. Перечень приложений
9. Подпись и дата
""".strip()

    hard_rule = """
ПРАВИЛО:

Отсутствие отдельных требований или срока
НЕ является основанием для отказа
в формировании документа.

Такие элементы подлежат фиксации
как «не согласовано» или «не указано».
""".strip()

    return with_legal_doctrine(
        f"""
{system}

====================
ФАКТИЧЕСКИЕ ДАННЫЕ
====================
{facts_block}

====================
КАТАЛОГ RAG
====================
{rag_sources_catalog}

====================
НОРМЫ ПРАВА (РК)
====================
{rag_text}

====================
ИНСТРУКЦИЯ
====================
{structure}

====================
ПРАВИЛО
====================
{hard_rule}

СФОРМИРУЙ ПРЕТЕНЗИЮ / ЖАЛОБУ.
ЮРИДИЧЕСКИЙ ДОКУМЕНТ.
""".strip()
    )
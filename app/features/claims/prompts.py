import os
from typing import Dict, List, Optional

from app.features.claims.claim_header import build_claim_header_instruction_block
from app.shared.legal_reality_system import with_legal_doctrine
from app.shared.professional_legal_standards import PRETRIAL_CLAIM_STANDARDS, SHARED_DRAFTING_DISCIPLINE
from app.shared.scenario_registry import SCENARIO_CLAIMS_COMPLAINT, SCENARIO_CLAIMS_PRETRIAL
from app.shared.legal_engine.schemas import LegalRunContext
from app.shared.legal_engine.stage3.prompt_block import format_legal_run_context_for_prompt


def build_claim_prompt(
    facts: Dict,
    verified_rag: List[Dict],
    *,
    rag_confidence: str = "strong",
    scenario_id: str | None = None,
    legal_run_context: Optional[LegalRunContext] = None,
) -> str:
    """
    Промпт претензии / жалобы.
    Жанр: односторонний досудебный / административный документ (не договор, не иск).
    """

    # =================================================
    # 1️⃣ FACTS
    # =================================================
    facts_block = f"""
ТИП ДОКУМЕНТА:
{facts.get("claim_type") or "Не согласовано"}

ЗАЯВИТЕЛЬ:
{facts.get("applicant") or "Не согласовано"}

АДРЕСАТ:
{facts.get("respondent") or "Не согласовано"}

ОТНОШЕНИЯ СТОРОН:
{facts.get("relationship") or "Не согласовано"}

СУТЬ НАРУШЕНИЯ:
{facts.get("violation") or "Не согласовано"}

ТРЕБОВАНИЯ ЗАЯВИТЕЛЯ:
{facts.get("demands") or "Не согласовано"}
""".strip()

    if facts.get("attachments"):
        facts_block += f"""

ДОКАЗАТЕЛЬСТВА / ПРИЛОЖЕНИЯ:
{facts.get("attachments")}
"""

    _digest = (facts.get("claims_intake_digest") or "").strip()
    if _digest:
        facts_block += f"""

СЖАТОЕ ПОНИМАНИЕ РАССКАЗА (intake, только следствие текста пользователя, без новых фактов):
{_digest}
"""

    if legal_run_context is not None:
        facts_block += "\n\n" + format_legal_run_context_for_prompt(legal_run_context)

    if str(facts.get("claims_legal_engine_safe_draft") or "").strip() == "1":
        facts_block += """

РЕЖИМ ОСТОРОЖНОГО ЧЕРНОВИКА (legal_engine):
- Не выдумывай факты; где данные пользователя неполные (см. отношения сторон / приложения), используй нейтральные формулировки и маркеры [УТОЧНИТЬ: …].
- Сохраняй жанр претензии или жалобы; не превращай в иск.
"""

    header_rules = build_claim_header_instruction_block(
        str(facts.get("applicant") or ""),
        str(facts.get("respondent") or ""),
    )

    rag_strength_block = ""
    if (rag_confidence or "").strip().lower() == "weak":
        rag_strength_block = """
ОПОРА НА RAG (СЛАБАЯ СВЯЗКА С ФАКТАМИ — СОБЛЮДАЙ):
- В «Правовые основания» не более 2–3 норм из блока ниже, только если связь с нарушением прямая;
- без категоричных формулировок «прямо из ст. …» при натянутой связи; лучше нейтрально («в части, касающейся …»);
- не заполняй абзац «для объёма»: лучше меньше норм, чем сомнительные;
- номера статей только из блока «НОРМЫ ПРАВА».
""".strip()

    # =================================================
    # 2️⃣ RAG — НОРМЫ ПРАВА (СТРОГО, БЕЗ ОТКАЗОВ)
    # =================================================
    rag_blocks: List[str] = []
    try:
        rag_body_cap = int(os.getenv("CLAIM_RAG_ARTICLE_TEXT_CHARS", "3200"))
    except ValueError:
        rag_body_cap = 3200
    rag_body_cap = max(800, min(rag_body_cap, 12000))

    for art in verified_rag or []:
        if not isinstance(art, dict):
            continue

        articles = art.get("articles")
        if not isinstance(articles, list) or not articles:
            continue

        first = articles[0]
        if not isinstance(first, dict):
            continue

        article_num = first.get("article")
        article_text = first.get("text")

        if not article_num or not article_text:
            continue

        source = art.get("source", "—")
        at = str(article_text).strip()
        if len(at) > rag_body_cap:
            at = at[:rag_body_cap].rstrip() + "\n[… фрагмент статьи усечён для претензии …]"

        rag_blocks.append(
            f"[{source}, статья {article_num}]\n{at}"
        )

    if not rag_blocks:
        rag_blocks.append(
            "Нормы права применяются в пределах переданных источников. "
            "Отсутствие конкретной статьи фиксируется как неполнота данных, "
            "а не как основание для отказа."
        )

    rag_text = "\n\n".join(rag_blocks)

    # =================================================
    # 3️⃣ КАТАЛОГ RAG (ФИКСИРОВАННЫЙ)
    # =================================================
    rag_sources_catalog = """
📚 КОДЕКСЫ
kz_gk_code
kz_pk_code
kz_nk_code
kz_tm_code
kz_koap_code
kz_appc_code
kz_tk_code

⚖️ НОРМАТИВНЫЕ ПОСТАНОВЛЕНИЯ ВС
kz_vs_np_civil_judgment_code
kz_vs_np_invalidity_of_transactions_code
kz_vs_np_llp_and_alp_code

📜 ЗАКОНЫ
kz_law_buh_code
kz_law_currency_control_code
kz_law_state_registration_code
kz_law_personal_data_code
kz_law_llp_code
kz_law_arbitration_code
""".strip()

    # =================================================
    # 4️⃣ SYSTEM ROLE — 🔒 РОЛЬ CLAIMS
    # =================================================
    _genre_lock = ""
    if scenario_id == SCENARIO_CLAIMS_PRETRIAL:
        _genre_lock = """
🔒 ЗАФИКСИРОВАННЫЙ ЖАНР (scenario lock): досудебная ПРЕТЕНЗИЯ / требование к контрагенту.
Нельзя оформлять как жалобу в госорган, как иск, как административное заявление в суд АППК или как юридическую консультацию.
Адресат — частный контрагент / организация / банк по гражданско-правовым отношениям (не надзорный орган).
""".strip()
    elif scenario_id == SCENARIO_CLAIMS_COMPLAINT:
        _genre_lock = """
🔒 ЗАФИКСИРОВАННЫЙ ЖАНР (scenario lock): ЖАЛОБА / обращение в ГОСУДАРСТВЕННЫЙ или ИНОЙ ОРГАН с публичными функциями.
Нельзя оформлять как досудебную претензию к контрагенту по гражданскому договору, как иск, как консультацию.
Тон и структура — обращение к органу власти/управления; требования должны соответствовать компетенции адресата (в пределах фактов пользователя).
""".strip()

    system = """
Ты — юрист-практик РК. Готовишь ОДИН документ: досудебная претензия, жалоба или обращение.

ЭТО НЕ:
- договор (не структурируй как договор сторон);
- исковое заявление (нет описания по ГПК, позиции истца/ответчика, судебных просьб);
- правовое заключение / меморандум (нет «в данной конфигурации…», «оценка допустимости судебной защиты», абстрактных выводов).

ЭТО:
- односторонний документ от заявителя к адресату;
- коротко по фактам, нарушению, нормам из RAG, требованиям, сроку ответа, приложениям;
- ориентир объёма: примерно 1–3 страницы (короче лучше длинного «реферата»); без вводных лекций и без многостраничного «заключения»;
- заканчивается датой и подписью (один блок реквизитов/подписи, без повторов).

СТРУКТУРА ТОЛЬКО ТАКАЯ (заголовки по смыслу, без «договорных» глав):
- кому адресовано (адресат);
- от кого (заявитель, контакты при наличии);
- заголовок («ПРЕТЕНЗИЯ» / «ЖАЛОБА» и тематическая строка при необходимости);
- факты (что произошло);
- нарушение (в чём суть претензии);
- правовые основания (кратко: ссылки на нормы из RAG с формулировкой «согласно ст. … [источник]»);
- требования (нумерованный список);
- срок ответа / исполнения;
- приложения (перечень);
- дата, подпись (при необходимости — реквизиты заявителя один раз).

ЗАПРЕЩЕНО ВКЛЮЧАТЬ РАЗДЕЛЫ, ХАРАКТЕРНЫЕ ДЛЯ ДОГОВОРА:
- Форс-мажор
- Ответственность сторон
- Порядок разрешения споров / подсудность / арбитражная оговорка (как в договоре)
- Заключительные положения
- Повторные блоки «Реквизиты и подписи сторон»
- Любая «юридическая оценка допустимости обращения в суд» отдельным пассажем

ЗАПРЕЩЕНО:
- консультационный тон и советы «можно также…»
- уголовные квалификации
- выдуманные статьи вне RAG
- указывать номера статей, которых нет в блоке «НОРМЫ ПРАВА» ниже (не дополняй кодекс из памяти)

ОБЯЗАТЕЛЬНО:
- нормы только из переданного блока RAG; в «Правовые основания» перечисли 2–5 отсылок в виде кратких тезисов «по ст. N [источник] — суть связи с нарушением»; каждая отсылка должна совпадать с одной из строк блока RAG (тот же источник и номер статьи); не используй норму, если связь с фактом выглядит натянутой;
- не оформляй документ как иск: не пиши «Истец», «Ответчик» (как стороны процесса), не включай госпошлину, цену иска, описательную/мотивировочную часть иска;
- после приложений → дата → подпись документ ЗАКАНЧИВАЕТСЯ; не раздувай «вторую волну» отдельными разделами;
  однако одна сжатая процессуально нейтральная фраза о праве защиты права иными способами при неисполнении (как в стандарте качества ниже) — допустима до подписи;
- пиши сухо, по шаблону претензии, без лишних абзацев.
"""
    if _genre_lock:
        system = _genre_lock + "\n\n" + system

    # =================================================
    # 5️⃣ СТРУКТУРА ПРЕТЕНЗИИ / ЖАЛОБЫ
    # =================================================
    structure = """
УСЛОВНЫЙ КАРКАС (без нумерации «как в учебнике», сразу текст документа):

Адресат → Заявитель → Заголовок → Факты → Нарушение → Правовые основания (нормы из RAG, кратко)
→ Требования → Срок ответа → Приложения → Дата и подпись (далее ничего).

Не пиши «Правовая оценка» отдельным разделом-эссе: только привязка факта к норме (2–6 коротких тезисов).
Не дублируй после подписи фразы про два экземпляра, подтверждение получения, неполучение ответа — конец документа на подписи/дате.
""".strip()

    hard_rule = """
ПРАВИЛО:

Отсутствие отдельных требований или срока
НЕ является основанием для отказа
в формировании документа.

Такие элементы подлежат фиксации
как «не согласовано» или «не указано».
""".strip()

    return with_legal_doctrine(
        f"""
{system}

====================
СТАНДАРТ КАЧЕСТВА (ПРЕТЕНЗИЯ / ЖАЛОБА)
====================
{SHARED_DRAFTING_DISCIPLINE}

{PRETRIAL_CLAIM_STANDARDS}

====================
ФАКТИЧЕСКИЕ ДАННЫЕ
====================
{facts_block}

====================
ШАПКА
====================
{header_rules}

{rag_strength_block}

====================
КАТАЛОГ RAG
====================
{rag_sources_catalog}

====================
НОРМЫ ПРАВА (РК)
====================
{rag_text}

====================
ИНСТРУКЦИЯ
====================
{structure}

====================
ПРАВИЛО
====================
{hard_rule}

СФОРМИРУЙ ОДНУ ПРЕТЕНЗИЮ / ЖАЛОБУ.
Соблюдай жанр; не добавляй договорные главы. Финал — дата и подпись, без текста после них.
""".strip()
    )
from aiogram.fsm.state import StatesGroup, State


# =========================
# CLAIMS FSM (КАНОН)
# РОЛЬ: ПРЕТЕНЗИЯ / ЖАЛОБА
# =========================

class ClaimsStates(StatesGroup):
    # 1️⃣ Тип обращения
    # (досудебная претензия / жалоба / обращение)
    claim_type = State()

    # 2️⃣ Заявитель
    # (ФИО или наименование)
    applicant = State()

    # 3️⃣ Адресат
    # (банк, контрагент, госорган, организация)
    respondent = State()

    # 4️⃣ Правоотношения
    # (договор, покупка, услуги, иное)
    relationship = State()

    # 5️⃣ Суть нарушения
    # (что нарушено, в чем проблема)
    violation = State()

    # 6️⃣ Требования
    # (что просим: вернуть, устранить, ответить и т.п.)
    demands = State()

    # 7️⃣ Приложения / доказательства
    # (договоры, чеки, переписка)
    attachments = State()

    # 8️⃣ Подтверждение
    confirm = State()
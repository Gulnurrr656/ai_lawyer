from typing import Any, Dict, List, Optional

from app.features.consult.consult_triage import CONSULT_CATEGORY_RU
from app.shared.legal_reality_system import with_legal_doctrine
from app.shared.professional_legal_standards import CONSULT_MEMO_STANDARDS, SHARED_DRAFTING_DISCIPLINE
from app.shared.rag_evidence_pack import render_evidence_pack_for_prompt
from app.shared.rag_first_contract import LEGAL_METHOD_BLOCK, RAG_FIRST_CORE
from app.shared.retrieval_profiles import get_retrieval_profile_notes
from app.shared.legal_engine.schemas import LegalRunContext
from app.shared.legal_engine.stage3.prompt_block import format_legal_run_context_for_prompt


def build_consult_prompt(
    facts: Dict,
    evidence_records: List[Dict[str, Any]],
    *,
    legal_run_context: Optional[LegalRunContext] = None,
) -> str:
    """
    ФИНАЛЬНЫЙ PROMPT КОНСУЛЬТАЦИИ.
    RAG-first: аргументация только из нормализованного LEGAL EVIDENCE PACK.
    """

    # =================================================
    # 1️⃣ FACTS (ФАКТИЧЕСКАЯ СИТУАЦИЯ)
    # =================================================
    clar = (facts.get("consult_clarifications") or "").strip()
    clar_block = (
        f"\n\nУТОЧНЕНИЯ (ответы пользователя на вопросы бота):\n{clar}"
        if clar
        else ""
    )
    cat = (facts.get("consult_primary_category") or "").strip()
    labels = (facts.get("consult_labels") or "").strip()
    is_mixed = (facts.get("consult_triage_mixed") or "").strip() == "1"
    cat_ru = CONSULT_CATEGORY_RU.get(cat, cat) if cat else "—"
    label_parts = [p.strip() for p in labels.split(",") if p.strip()]
    labels_ru = (
        ", ".join(CONSULT_CATEGORY_RU.get(lb, lb) for lb in label_parts)
        if label_parts
        else "—"
    )
    class_block = ""
    if cat or labels or is_mixed:
        class_block = (
            "\n\nПРЕДВАРИТЕЛЬНАЯ КЛАССИФИКАЦИЯ (эвристика по ключевым словам, не судебный вывод):\n"
            f"Доминирующая метка (RU): {cat_ru}\n"
            f"Связанные метки (RU): {labels_ru}\n"
            f"Смешанный кейс (несколько контуров): {'да' if is_mixed else 'нет'}"
        )

    _digest = (facts.get("consult_intake_digest") or "").strip()
    digest_block = (
        f"\n\nСЖАТОЕ ПОНИМАНИЕ ЗАПРОСА (интерпретатор intake, без добавления новых фактов):\n{_digest}"
        if _digest
        else ""
    )

    safe_consult = (facts.get("consult_legal_engine_safe_draft") or "").strip() == "1"
    safe_block = (
        "\n\nРЕЖИМ ОСТОРОЖНОГО ЧЕРНОВИКА (legal_engine): пользователь подтвердил запуск при неполных "
        "мягких полях. Добавь нейтральные дисклеймеры; используй маркеры вида [УТОЧНИТЬ: …] "
        "вместо домыслов; не заполняй пробелы выдуманными фактами, датами или номерами дел."
        if safe_consult
        else ""
    )

    facts_block = f"""
ТЕМА ВОПРОСА:
{facts.get("topic") or facts.get("question")}

ОПИСАНИЕ СИТУАЦИИ:
{facts.get("situation") or facts.get("context")}

ЦЕЛЬ КОНСУЛЬТАЦИИ:
{facts.get("goal") or facts.get("goals")}

РИСКИ / ОГРАНИЧЕНИЯ:
{facts.get("constraints") or "не указаны"}
{class_block}{clar_block}{digest_block}{safe_block}
""".strip()

    stage3_block = ""
    if legal_run_context is not None:
        stage3_block = "\n\n" + format_legal_run_context_for_prompt(legal_run_context)

    facts_block = facts_block + stage3_block

    # =================================================
    # 2️⃣ RAG — LEGAL EVIDENCE PACK (нормализованный)
    # =================================================
    rag_text = render_evidence_pack_for_prompt(evidence_records)

    _profile = get_retrieval_profile_notes("consult")
    if _profile:
        lines = "\n".join(f"- {k}: {v}" for k, v in _profile.items())
        retrieval_focus_block = f"\n\nАКЦЕНТ RETRIEVAL (consult):\n{lines}"
    else:
        retrieval_focus_block = ""

    # =================================================
    # 3️⃣ КАТАЛОГ RAG (ИНФОРМАЦИОННЫЙ)
    # =================================================
    rag_sources_catalog = """
📚 КОДЕКСЫ
kz_gk_code
kz_pk_code
kz_nk_code
kz_tm_code
kz_koap_code
kz_appc_code
kz_tk_code

⚖️ НОРМАТИВНЫЕ ПОСТАНОВЛЕНИЯ ВС
kz_vs_np_civil_judgment_code
kz_vs_np_civil_procedure_norms_code
kz_vs_np_invalidity_of_transactions_code
kz_vs_np_llp_and_alp_code

📜 ЗАКОНЫ
kz_law_buh_code
kz_law_currency_control_code
kz_law_state_registration_code
kz_law_personal_data_code
kz_law_llp_code
kz_law_arbitration_code
""".strip()

    # =================================================
    # 4️⃣ SYSTEM ROLE — 🔒 ФИКСАЦИЯ РОЛИ КОНСУЛЬТА
    # =================================================
    system = """
Ты формируешь результат в жанре юридической консультации (legal memo / legal opinion) по праву Республики Казахстан.
Пиши как сильный практикующий юрист: строгий, процессуально грамотный, ориентированный на применимые нормы и риски.
Опирайся только на подтверждённые факты пользователя и на LEGAL EVIDENCE PACK ниже, без выдуманных реквизитов и норм.

ТВОЯ РОЛЬ:
➡️ ЮРИДИЧЕСКИЙ КОНСУЛЬТАНТ (не суд, не сторона процесса в документе).

ТЫ НЕ:
- не пишешь договоры
- не составляешь заявления
- не формируешь претензии
- не создаёшь процессуальные документы (в т.ч. полный текст иска с «вводной частью»)

ТЫ ДЕЛАЕШЬ ТОЛЬКО:
- квалификация ситуации
- применимые нормы из пакета (с привязкой к фактам)
- юридические риски и уязвимости
- сильные и слабые стороны позиции (в рамках фактов и пакета)
- какие документы и данные нужны
- что делать дальше и перспективы защиты (без гарантии исхода)

СТИЛЬ:
- чётко, по делу, без воды, без чат-бота; укажи пробелы в фактах там, где без них нельзя делать вывод.
"""

    # =================================================
    # 5️⃣ СТРУКТУРА КОНСУЛЬТАЦИИ
    # =================================================
    structure = """
СТРУКТУРА КОНСУЛЬТАЦИИ (СТРОГО ПО РАЗДЕЛАМ С ЗАГОЛОВКАМИ):

Итоговый текст обязан явно покрыть все 6 элементов из блока «СТАНДАРТ КАЧЕСТВА» (краткий вывод; анализ фактов; нормы из RAG; риски; шаги; пробелы в данных).
Нумерация ниже детализирует подачу; при объединении разделов не пропускай ни один из шести элементов.

1. ПРЕДВАРИТЕЛЬНАЯ КВАЛИФИКАЦИЯ
   Какие правоотношения вы видите по фактам; оговорка, что очная оценка с документами может изменить акценты.
   Если по классификации/фактам видно несколько контуров — в начале 2–4 предложения: «вопрос состоит из …», без «одной общей массы» на все темы.

2. ОСНОВНОЙ ВЫВОД
   Прямой ответ на цель консультации; нормы из RAG с привязкой к ситуации.
   При смешанном кейсе: после пункта 1 дайте 2–3 подпункта с заголовками вида «По контуру: …» (труд / долги / налоги / госорган / имущество-ИП и т.д.) — кратко по каждому, без общего пересказа учебника.

3. РИСКИ И СЛАБЫЕ МЕСТА
   Процессуальные, материально-правовые, сроки, доказательства; без запугивания.
   По смешанному кейсу — отдельно по каждому затронутому контуру (коротко).

4. ЧТО ДЕЛАТЬ ДАЛЬШЕ
   По шагам: 3–7 коротких пунктов (что проверить, куда обратиться, чего избегать).
   Укажите, какие документы собрать (переписка, акты, уведомления органа, выписки) и куда логично обращаться дальше по профилю дела.

5. ЧТО МОЖНО ПОДГОТОВИТЬ СЛЕДУЮЩИМ ШАГОМ (ТОЛЬКО ОРИЕНТИРЫ, БЕЗ ТЕКСТОВ ДОКУМЕНТОВ)
   Перечислите релевантное из списка и поясните коротко зачем:
   • досудебное обращение к контрагенту (претензионный порядок)
   • обращение в государственный орган (заявление / жалоба по компетенции)
   • судебная защита (гражданский иск по ГПО)
   • пакет документов / выписки
   • отдельный разбор риска или текста сделки

6. ПЕРСПЕКТИВЫ И ОГРАНИЧЕНИЯ
   Кратко: что может усилить позицию, что может привести к отказу/рискам, без обещания результата.

ТОН И ОБЪЁМ:
- Не делайте реферат «обо всём сразу»; приоритет — цель пользователя и доминирующий контур из фактов.
- Избегайте воды и обобщений без привязки к переданным фактам и RAG.

Если факты неполные — прямо укажите, какие данные критичны до юридически уверенных выводов.
""".strip()

    hard_rules = """
ЗАПРЕЩЕНО:
- писать «договор»
- писать «заявление»
- писать «претензию»
- использовать формулировки процессуальных документов

РАЗРЕШЕНО:
- объяснять
- предупреждать
- рекомендовать варианты
""".strip()

    genre_guard = """
ЖАНР — СТРОГО ЮРИДИЧЕСКАЯ КОНСУЛЬТАЦИЯ (НЕ ШАБЛОН ДОКУМЕНТА):
Вы отвечаете как консультант по живому кейсу. Это не текст договора, не претензия, не заявление в орган, не исковое заявление, не акт и не приложение к ним — даже «в конце для образца».

ЗАПРЕТ НА ТИПОВЫЕ РАЗДЕЛЫ И ОФОРМЛЕНИЕ ДОГОВОРА/ДОКУМЕНТА:
- не включать блоки с заголовками уровня типового договора: Ответственность сторон; Разрешение споров;
  Заключительные положения; Форс-мажор / обстоятельства непреодолимой силы; Порядок изменения или расторжения договора;
  Приложения; Перечень приложений; Подсудность; Применимое право — как отдельные главы
- не указывать реквизиты сторон, банковские реквизиты, ИНН, БИК, р/с, КБе в виде шаблонного блока «для оплаты»
- не оформлять подписи сторон, М.П., п.п., подпись ____________, расшифровки для подписания
- не дублировать один и тот же блок реквизитов или заключительных фраз шаблона

ДОПУСТИМО В ЖАНРЕ КОНСУЛЬТАЦИИ:
- аналитически говорить об ответственности, рисках спора, досудебном/судебном порядке — в связи с фактами и RAG, без структуры «глава договора»
- в пункте 5 перечислять, какой тип документа или шаг может понадобиться дальше, без текста и без реквизитов

ФИНАЛ:
После разделов 1–6 по структуре консультации текст должен заканчиваться. Не добавляйте «хвост» в виде типового договора или повторных реквизитов.
""".strip()

    return with_legal_doctrine(
        f"""
{system}

====================
СТАНДАРТ КАЧЕСТВА (КОНСУЛЬТАЦИЯ)
====================
{SHARED_DRAFTING_DISCIPLINE}

{CONSULT_MEMO_STANDARDS}

====================
ФАКТИЧЕСКИЕ ДАННЫЕ
====================
{facts_block}
{retrieval_focus_block}

====================
КАТАЛОГ RAG
====================
{rag_sources_catalog}

====================
RAG-FIRST И МЕТОД
====================
{RAG_FIRST_CORE}

{LEGAL_METHOD_BLOCK}

====================
LEGAL EVIDENCE PACK
====================
{rag_text}

====================
ИНСТРУКЦИЯ
====================
{structure}

====================
ОБЯЗАТЕЛЬНЫЕ ОГРАНИЧЕНИЯ
====================
{hard_rules}

====================
ЖАНР: ТОЛЬКО КОНСУЛЬТАЦИЯ
====================
{genre_guard}

ДАЙ ЮРИДИЧЕСКУЮ КОНСУЛЬТАЦИЮ.
НЕ СОЗДАВАЙ ДОКУМЕНТЫ И НЕ ДОПИСЫВАЙ ШАБЛОН ДОГОВОРА/РЕКВИЗИТЫ/ПОДПИСИ.
""".strip()
    )
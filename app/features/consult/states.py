from aiogram.fsm.state import StatesGroup, State


# =========================
# CONSULT FSM (КАНОН)
# РОЛЬ: ЮРИДИЧЕСКАЯ КОНСУЛЬТАЦИЯ
# =========================

class ConsultStates(StatesGroup):
    # 1️⃣ Вопрос / тема консультации
    # (долг, банк, налог, спор, госорган, договор и т.д.)
    topic = State()

    # 2️⃣ Описание ситуации
    # (что произошло, кто участвует, в чем проблема)
    situation = State()

    # 3️⃣ Цель консультации
    # (понять права, выбрать стратегию, оценить риски)
    goal = State()

    # 4️⃣ Риски / ограничения
    # (сроки, давление, проверки, угрозы, штрафы)
    constraints = State()

    # 5️⃣ Уточняющие вопросы (после триажа, если мало фактов или смешанный кейс)
    clarify = State()

    # 6️⃣ Подтверждение перед генерацией
    confirm = State()
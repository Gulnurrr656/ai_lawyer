def _commercial_arithmetic_context_lines(facts: Mapping[str, Any]) -> str:
    """Опционально: когда есть общая сумма + цена за единицу + предмет — усилить приоритет явной суммы."""
    triplets: Tuple[Tuple[str, str, str, str], ...] = (
        ("supply_price", "supply_price_unit", "goods", "поставке"),
        ("service_price", "service_price_unit", "service_object", "оказании услуг"),
        ("work_price", "work_price_unit", "work_object", "подряде"),
        ("manufacture_price", "manufacture_price_unit", "product", "изготовлении"),
    )
    lines: List[str] = []
    for total_k, unit_k, subj_k, label in triplets:
        tv = facts.get(total_k)
        uv = facts.get(unit_k)
        sv = facts.get(subj_k)
        if not all(
            isinstance(x, str) and x.strip() for x in (tv, uv, sv)
        ):
            continue
        lines.append(
            f"— Контекст ({label}): заполнены `{total_k}`, `{unit_k}` и `{subj_k}`. В §6 допустимо показать расчёт "
            f"«цена за единицу × количество», если числа однозначно выводятся из фактов; итоговая договорная сумма из "
            f"`{total_k}` считается приоритетной: не заменяй её результатом умножения без явного противоречия или опечатки во фактах; "
            "если сомневаешься — закрепи общую сумму как согласованную, а расхождение отсложи на спецификацию/допсоглашение.\n"
        )
    return "".join(lines)


def build_commercial_consistency_rules_pin(facts: Mapping[str, Any]) -> str:
    """
    Краткие обязательные правила согласованности цены, оплаты и НДС (без изменения FACTS).
    Вставляется в промпт рядом с критическими фактами.
    """
    keys = (
        "vat_mode",
        "payment_terms",
        "payment_due",
        "price_and_payment",
        "supply_price",
        "supply_price_unit",
        "service_price",
        "service_price_unit",
        "work_price",
        "work_price_unit",
        "manufacture_price",
        "manufacture_price_unit",
        "rent_price",
    )
    if not any(
        isinstance(facts.get(k), str) and str(facts.get(k)).strip() for k in keys
    ):
        return ""

    vm = (facts.get("vat_mode") if isinstance(facts.get("vat_mode"), str) else "") or ""
    vm = vm.strip()
    vm_line = ""
    if vm in ("с НДС", "без НДС"):
        vm_line = (
            f"— Статус НДС в договоре должен соответствовать факту `vat_mode` = «{vm}» во всех разделах о цене, "
            "оплате и налогах (§6–8); не сочетай взаимоисключающие формулировки («включён» / «не подлежит» / «без НДС») без явной оговорки из фактов.\n"
        )
    elif vm == "не знаю":
        vm_line = (
            "— `vat_mode` = «не знаю»: не фиксируй категорично включение или отсутствие НДС в сумме; используй нейтральные формулировки "
            "и отсылку к закону/порядку определения налоговой квалификации, без противоречий между §6 и §8.\n"
        )

    return (
        "==============================\n"
        "КОММЕРЧЕСКАЯ СОГЛАСОВАННОСТЬ (цена · оплата · НДС)\n"
        "==============================\n"
        "— Раздел 6 «Цена договора»: суммы, валюта, при необходимости цена за единицу и порядок расчёта; не смешивай с графиком платежей.\n"
        "— Раздел 7 «Порядок оплаты»: авансы, этапы, счета-фактуры при необходимости; сроки конкретных платежей — по факту `payment_due` "
        "(если он задан отдельно); если в фактах порядок и сроки уже разделены — сохрани разделение в тексте.\n"
        "— Если одновременно заданы общая сумма в поле цены и цена за единицу / объём в предмете: при однозначных числах можно показать "
        "согласованный расчёт «цена × количество»; если пользователь явно указал общую сумму — не заменяй её иным итогом без явной "
        "ошибки или расхождения во фактах; при двусмысленности укажи, что итог определяется по спецификации/приложению.\n"
        "— Поле `price_and_payment` (аренда и legacy): те же суммы и налоговый контекст цены вынеси в §6, порядок и сроки внесения "
        "платежей — в §7; дублирование одного абзаца в обоих разделах недопустимо — структурируй по смыслу.\n"
        "— Раздел 8 «НДС и налоги»: согласуй с `vat_mode` и с тем, как в §6 описана сумма (в т.ч. включён/не включён налог); "
        "не дублируй противоречивые налоговые квалификации в §6 и §8.\n"
        f"{_commercial_arithmetic_context_lines(facts)}"
        f"{vm_line}"
    ).strip()


def build_contract_prompt(
    *,
    facts: dict,
    verified_rag: list,
    rag_display_groups: Optional[Sequence[Tuple[str, Sequence[dict]]]] = None,
    node_evidence_packages: Optional[Sequence[Mapping[str, Any]]] = None,
    legal_run_context: Optional[LegalRunContext] = None,
) -> str:
    """
    КАНОНИЧЕСКИЙ PROMPT ДОГОВОРА
    🔒 Разделы фиксированы
    🔒 Названия разделов НЕ МЕНЯТЬ
    🔒 Ни один раздел нельзя опускать
    """

    # -------------------------------
    # helpers
    # -------------------------------
    def raw(key: str) -> str:
        v = facts.get(key)
        if isinstance(v, str) and v.strip():
            return v.strip()
        return ""

    def block(*keys: str) -> str:
        for k in keys:
            v = raw(k)
            if v:
                return v
        return "Не применяется"

    evidence_records = build_evidence_records(list(verified_rag))
    evidence_pack_text = render_evidence_pack_for_prompt(evidence_records)

    _cret = get_retrieval_profile_notes("contract")
    contract_retrieval_block = ""
    if _cret:
        lines_parts: List[str] = []
        for k, v in _cret.items():
            if k == "retrieval_axes" and isinstance(v, tuple):
                lines_parts.append(f"{k}:")
                for ax in v:
                    lines_parts.append(f"  - {ax}")
            else:
                lines_parts.append(f"- {k}: {v}")
        contract_retrieval_block = (
            "\n\n==============================\n"
            "АКЦЕНТЫ RETRIEVAL (contract)\n"
            "==============================\n" + "\n".join(lines_parts)
        )

    # -------------------------------
    # RAG BLOCK (СТАБИЛЬНЫЙ + опционально по кластерам сборки)
    # -------------------------------
    rag_block_parts: List[str] = []

    if rag_display_groups:
        rag_block_parts.append(
            "Ориентир по смысловым блокам договора (подбор норм по legal assembly; "
            "один источник может фигурировать в нескольких блоках):"
        )
        for heading, chunks in rag_display_groups:
            if not heading:
                continue
            rag_block_parts.append(f"\n### {heading}")
            sub: List[str] = []
            for a in chunks:
                line = _format_rag_entry(a if isinstance(a, dict) else {})
                if line:
                    sub.append(line)
            if sub:
                rag_block_parts.extend(sub)
            else:
                rag_block_parts.append("— для этого блока чанки не отобраны")
        rag_block_parts.append(
            f"\nВсего уникальных статей в подборке: {len(verified_rag)}."
        )

    rag_lines: List[str] = []
    for a in verified_rag:
        if not isinstance(a, dict):
            continue
        line = _format_rag_entry(a)
        if line:
            rag_lines.append(line)

    if not rag_lines:
        rag_lines.append("— нормы права определяются в рамках переданных источников")

    if rag_block_parts:
        rag_block = "\n".join(rag_block_parts) + "\n\n================\nПолный перечень источников (компактно):\n" + "\n".join(rag_lines)
    else:
        rag_block = "\n".join(rag_lines)

    node_evidence_section = _format_node_evidence_for_prompt(node_evidence_packages)

    _pk = str(facts.get("profile_key") or facts.get("contract_type") or "").strip().lower()
    profile_addon = ""

from __future__ import annotations

from typing import Any, Dict, List

from app.shared.legal_reality_system import with_legal_doctrine


def build_contract_prompt(*, facts: dict, verified_rag: list) -> str:
    """
    КАНОНИЧЕСКИЙ PROMPT ДОГОВОРА
    🔒 Разделы фиксированы
    🔒 Названия разделов НЕ МЕНЯТЬ
    🔒 Ни один раздел нельзя опускать
    """

    # -------------------------------
    # helpers
    # -------------------------------
    def raw(key: str) -> str:
        v = facts.get(key)
        if isinstance(v, str) and v.strip():
            return v.strip()
        return ""

    def block(*keys: str) -> str:
        for k in keys:
            v = raw(k)
            if v:
                return v
        return "Не применяется"

    # -------------------------------
    # RAG BLOCK (СТАБИЛЬНЫЙ)
    # -------------------------------
    rag_lines = []
    for a in verified_rag:
        if not isinstance(a, dict):
            continue
        src = a.get("source")
        title = a.get("title", "")
        if src:
            rag_lines.append(f"- {src}: {title}")

    if not rag_lines:
        rag_lines.append("— нормы права определяются в рамках переданных источников")

    rag_block = "\n".join(rag_lines)

    # -------------------------------
    # PROMPT
    # -------------------------------
    return with_legal_doctrine(
        f"""
ТЫ — ЮРИСТ-ПРАКТИК РЕСПУБЛИКИ КАЗАХСТАН.
Ты формируешь полный, юридически допустимый договор.

❗ ОБЯЗАТЕЛЬНЫЕ ПРАВИЛА РАБОТЫ:
• Структура договора является фиксированной. Названия разделов сохраняются в установленном виде.
• Разделы не объединяются и не исключаются из текста. Каждый раздел должен присутствовать в договоре.
• Раздел считается корректно сформированным, если он присутствует в тексте договора,
  даже если его содержание указано как: «Не согласовано», «Не применяется» или «Определяется отдельно».
• При отсутствии согласованных условий по разделу необходимо прямо указывать: «Не согласовано».
• Если соответствующее условие по своей природе не подлежит применению к данному договору,
  необходимо указывать: «Не применяется».
• Неполнота условий, отсутствие отдельных сведений или неуточнённость параметров
  не является основанием для отказа в формировании договора.
• В таких случаях договор формируется с корректной фиксацией отсутствующих условий
  без додумывания фактов и без юридической имитации.

==============================
📜 НОРМАТИВНАЯ БАЗА (RAG)
==============================
{rag_block}

==============================
📄 СТРУКТУРА ДОГОВОРА
==============================

1. ПРЕДМЕТ ДОГОВОРА
{block(
    "service_object",
    "work_object",
    "rent_object",
    "goods",
    "product",
    "subject_of_contract",
)}

2. ОБЪЁМ И СОДЕРЖАНИЕ УСЛУГ / РАБОТ
{block(
    "service_scope",
    "work_kind",
    "manufacture_kind",
)}

2.1. ПОРЯДОК ОКАЗАНИЯ УСЛУГ
{block(
    "service_schedule",
    "performance_terms",
)}

3. ТЕХНИЧЕСКОЕ ЗАДАНИЕ / СПЕЦИФИКАЦИЯ
{block(
    "service_tz",
    "work_tz",
    "tz",
    "technical_task",
    "specification",
    "rent_specification",
)}

4. СРОКИ И ПОРЯДОК ИСПОЛНЕНИЯ
{block(
    "service_term",
    "work_term",
    "manufacture_term",
    "rent_term",
    "supply_term",
)}

5. ГРАФИК ВЫПОЛНЕНИЯ (ЕСЛИ ПРИМЕНИМО)
{block("service_schedule")}

6. ЦЕНА ДОГОВОРА
{block(
    "service_price",
    "work_price",
    "manufacture_price",
    "rent_price",
    "supply_price",
)}

7. ПОРЯДОК ОПЛАТЫ
{block("payment_terms")}

8. НДС И НАЛОГИ
{block("vat_mode")}

9. ПРИЁМКА РЕЗУЛЬТАТОВ
{block(
    "service_acceptance",
    "work_acceptance",
    "manufacture_acceptance",
    "supply_acceptance",
)}

10. КАЧЕСТВО И ГАРАНТИИ
{block(
    "quality_requirements",
    "quality_guarantees",
    "warranty",
)}

11. ОТВЕТСТВЕННОСТЬ СТОРОН
{block(
    "service_liability",
    "work_liability",
    "manufacture_liability",
    "supply_liability",
    "liability_mode",
)}

12. ОБЕСПЕЧЕНИЕ ИСПОЛНЕНИЯ ОБЯЗАТЕЛЬСТВ
{block(
    "service_security",
    "work_security",
    "manufacture_security",
    "supply_security",
    "security_deposit",
)}

13. ФОРС-МАЖОР
{block("force_majeure")}

14. КОНФИДЕНЦИАЛЬНОСТЬ
{block("confidential")}

15. ПЕРСОНАЛЬНЫЕ ДАННЫЕ
{block("pd")}

16. ПОРЯДОК УВЕДОМЛЕНИЙ
{block("notice")}

17. РАЗРЕШЕНИЕ СПОРОВ
{block("dispute")}

18. РАСТОРЖЕНИЕ ДОГОВОРА
{block("termination")}

19. ЗАКЛЮЧИТЕЛЬНЫЕ ПОЛОЖЕНИЯ
(действие договора, изменения, толкование условий)

20. РЕКВИЗИТЫ И ПОДПИСИ СТОРОН

==============================
📌 ТРЕБОВАНИЯ К ТЕКСТУ
==============================
- Юридически строгий стиль
- Использовать нормы из RAG
- Не додумывать факты
- Отсутствующие условия фиксировать, а не использовать как основание для отказа
- Объём не менее 15 страниц
""".strip()
    )



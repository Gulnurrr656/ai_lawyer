def _contract_pin_char_limits() -> Tuple[int, int]:
    """Лимиты pin: CONTRACT_PIN_FIELD_CHARS, CONTRACT_PIN_TOTAL_CHARS (fallback 4000 / 10000)."""
    try:
        per_field = int(os.getenv("CONTRACT_PIN_FIELD_CHARS", "4000"))
    except ValueError:
        per_field = 4000
    try:
        total_soft = int(os.getenv("CONTRACT_PIN_TOTAL_CHARS", "10000"))
    except ValueError:
        total_soft = 10000
    return max(256, per_field), max(512, total_soft)


def _pin_clip(s: str, max_len: int) -> str:
    t = (s or "").strip()
    if len(t) <= max_len:
        return t
    return t[: max(0, max_len - 1)] + "…"



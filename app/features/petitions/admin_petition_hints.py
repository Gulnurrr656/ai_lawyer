"""Процессуальные подсказки для административного заявления (ветка A petitions)."""

from __future__ import annotations

import re
from typing import Any, Mapping


def extract_registration_tokens(text: str) -> list[str]:
    """Номера обращений вида REG-KZ-2026-44128 и похожие идентификаторы из текста пользователя."""
    if not (text or "").strip():
        return []
    blob = text
    found: list[str] = []
    for pattern in (
        r"\bREG-[A-Za-z]{2}-\d{4}-\d+\b",  # REG-KZ-2026-44128
        r"\b(?:REG|reg)[-_][A-Za-z0-9]+(?:[-_][A-Za-z0-9]+)+\b",
    ):
        for m in re.finditer(pattern, blob, flags=re.IGNORECASE):
            t = m.group(0).strip()
            if t and t not in found:
                found.append(t)
    return found[:12]


def build_admin_procedural_addon(facts: Mapping[str, Any]) -> str:
    addressee = str(facts.get("addressee") or "").strip()
    situation = str(facts.get("situation") or "")
    requests = str(facts.get("requests") or "")
    evidence = str(facts.get("evidence") or "")
    attachments = str(facts.get("attachments") or "")
    blob = f"{situation}\n{requests}\n{evidence}\n{attachments}"
    tokens = extract_registration_tokens(blob)

    court_block = (
        "АДРЕСАТ / СУД (АППК РК):\n"
        "- В шапке указывай **конкретный** административный суд: полное наименование из поля «АДРЕСАТ» пользователя.\n"
        "- КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО в качестве адресата писать «суд Республики Казахстан», «в Республике Казахстан» "
        "или любую формулировку без **конкретного** наименования суда (районный / специализированный "
        "административный суд и т.п.).\n"
        "- Подсудность обжалования бездействия госоргана — по правилам ст. 102 АППК РК (по месту нахождения органа); "
        "формулируй это в связке с фактами и нормами из verified_rag, не выдумывай название суда, если пользователь "
        "его не дал — тогда нейтральный плейсхолдер: «В ________________ (районный административный суд по месту "
        "нахождения органа — уточнить)».\n"
    )
    if addressee and len(addressee) < 12:
        court_block += (
            "- Поле адресата короткое: либо дополни из контекста фактов, либо плейсхолдер + явное «уточнить».\n"
        )

    title_block = (
        "НАЗВАНИЕ ДОКУМЕНТА:\n"
        "- Предпочтительно: «Административное исковое заявление» или «Жалоба на бездействие государственного органа» "
        "(по смыслу фактов и терминологии АППК из verified_rag), плюс отдельная строка предмета.\n"
        "- Избегай сухого одного слова «Заявление» без уточнения вида административного процесса.\n"
    )

    deadline_block = (
        "СРОКИ ОКАЗАНИЯ ГОСУСЛУГИ / БЕЗДЕЙСТВИЕ:\n"
        "- Если из фактов следует оказание государственной услуги — укажи **какой** установленный срок нарушен "
        "(если пользователь или нормы из verified_rag позволяют: например, типовые сроки по соответствующим правилам; "
        "если точная цифра не следует из данных — «срок подлежит уточнению по акту/правилам оказания услуги»).\n"
        "- Закрепи сравнение: срок по правилам / фактическое бездействие / просрочка на N календарных или рабочих дней "
        "(N — из фактов или плейсхолдер «____»).\n"
    )

    norms_block = (
        "РОЛИ НОРМ АППК (ИЗ verified_rag, БЕЗ ВЫДУМЫВАНИЯ НОМЕРОВ):\n"
        "- Статья 93 АППК (если есть в RAG) — как правило о **форме и содержании** жалобы/заявления; "
        "не подавай её как единственное «основание» признания бездействия незаконным.\n"
        "- Для существа спора опирайся на нормы об обязанностях органа, правах заявителя, сроках и т.п. "
        "(например, ст. 20, 22, 44 АППК — **только если текст статьи есть в verified_rag**).\n"
        "- Статья 102 АППК — подсудность; ст. 122 АППК — распределение судебных расходов (связь с ГПК), формулируй осторожно.\n"
    )

    costs_block = (
        "СУДЕБНЫЕ РАСХОДЫ И ОБЕСПЕЧИТЕЛЬНЫЕ МЕРЫ:\n"
        "- Расходы: допустима мягкая формулировка вроде «взыскать с ответчика судебные расходы в случае удовлетворения "
        "требований» (с опорой на verified_rag, в т.ч. ст. 122 АППК при наличии).\n"
        "- Обеспечительные меры — только при кратком отдельном обосновании и если следует из фактов; не делай их "
        "главным требованием без нужды.\n"
    )

    reg_block = ""
    if tokens:
        reg_block = (
            "ИДЕНТИФИКАТОРЫ ИЗ ТЕКСТА ПОЛЬЗОВАТЕЛЯ (повтори в требованиях):\n"
            + "\n".join(f"- {t}" for t in tokens)
            + "\n"
        )
    else:
        reg_block = (
            "Если в фактах есть номер обращения / регистрационный номер — повтори его во вводной части и в требованиях.\n"
        )

    summary_block = (
        "СВОДКА ПО НОРМАМ:\n"
        "- Не делай акцент на формулировках «отсутствует прямая норма в RAG»; не превращай пробелы базы в главный аргумент.\n"
        "- Кратко укажи применённые нормы и риски без тональности «отказ в удовлетворении из-за RAG».\n"
    )

    return "\n".join(
        [
            court_block.strip(),
            title_block.strip(),
            deadline_block.strip(),
            norms_block.strip(),
            costs_block.strip(),
            reg_block.strip(),
            summary_block.strip(),
        ]
    ).strip()

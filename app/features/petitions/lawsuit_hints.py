# app/features/petitions/lawsuit_hints.py
"""Короткие процессуальные подсказки для искового заявления (ветка B), без нового intake."""

from __future__ import annotations

from typing import Any, Dict, Mapping


def _low(s: str) -> str:
    return (s or "").strip().lower()


def infer_subject_matters(situation: str, requests: str) -> str:
    blob = f"{situation} {requests}".lower()
    parts: list[str] = []
    if any(x in blob for x in ("расторж", "расторгнуть", "прекращен", "расторжение договор")):
        parts.append("о расторжении договора / прекращении обязательства (если следует из фактов)")
    if any(x in blob for x in ("неустойк", "пеня", "штраф", "пени")):
        parts.append("о взыскании неустойки (пени) — с указанием периода/расчёта, насколько позволяют факты")
    if any(x in blob for x in ("убытк", "ущерб", "вред")):
        parts.append("о взыскании убытков / вреда")
    if any(x in blob for x in ("взыск", "долг", "задолжен", "вернуть деньг", "оплат")):
        parts.append("о взыскании денежной суммы (основной долг / задолженность)")
    if any(x in blob for x in ("обязать", "понудител", "передать", "выполнить", "истребовать")):
        parts.append("об обязании совершить определённые действия (понуждение к исполнению обязательства)")
    if any(x in blob for x in ("признан", "признать право", "неправомерн")):
        parts.append("о признании права / неправомерности действий (если следует из фактов)")
    if not parts:
        return (
            "сформулируй предмет иска явно в заголовке и во вводной части по смыслу фактов "
            "(взыскание суммы / расторжение / неустойка / убытки / понуждение и т.п.)."
        )
    return (
        "в заголовке и вводной части закрепи предмет иска, в частности: "
        + "; ".join(parts)
        + "."
    )


def build_lawsuit_procedural_addon(facts: Mapping[str, Any]) -> str:
    situation = str(facts.get("situation") or "")
    requests = str(facts.get("requests") or "")
    addressee = str(facts.get("addressee") or "").strip()
    opponent = str(facts.get("opponent") or "").strip()

    addressee_l = _low(addressee)
    court_uncertain = (
        not addressee
        or "уточн" in addressee_l
        or "неизвест" in addressee_l
        or addressee_l in {"суд", "районный суд", "городской суд"}
        or len(addressee) < 8
    )

    subj = infer_subject_matters(situation, requests)

    court_rule = (
        "НАИМЕНОВАНИЕ СУДА И ПОДСУДНОСТЬ:\n"
        "- В шапке укажи суд ТОЛЬКО так, как передал пользователь в поле «суд/адресат». "
        "Не подменяй и не «додумывай» конкретный районный/городской суд.\n"
        "- Если наименование суда не задано, расплывчато или очевидно требует уточнения подсудности — "
        "используй нейтральную форму с явным плейсхолдером, например: "
        "«В _________________________ (наименование суда по правилам подсудности ГПК РК — уточнить)», "
        "или: «В суд по месту … (указать основание подсудности / место нахождения ответчика — уточнить)».\n"
        "- В разделе «Подсудность» ссылайся на нормы ГПК из verified_rag; не утверждай конкретный суд как факт без данных пользователя.\n"
    )
    if court_uncertain:
        court_rule += (
            "- ПОЛЬЗОВАТЕЛЬСКОЕ ЗНАЧЕНИЕ СУДА ВЫГЛЯДИТ НЕПОЛНЫМ: ОБЯЗАТЕЛЬНО плейсхолдер вместо выдуманного названия суда.\n"
        )

    header_rule = (
        "ШАПКА ИСКА (аккуратно, процессуально):\n"
        "- После наименования суда — истец (как в данных; при необходимости адрес/контакт — если есть в данных).\n"
        "- Ответчик: полное ФИО или наименование; ИИН/БИН — если указаны пользователем; "
        "адрес (юридический и/или фактический). Если в данных адрес ответчика отсутствует или неполон — "
        "отдельной строкой: «Адрес ответчика: (уточнить)».\n"
        "- Заголовок документа: «ИСКОВОЕ ЗАЯВЛЕНИЕ» и отдельной строкой предмет: «о …» "
        f"({subj})\n"
    )

    opposite_rule = ""
    if opponent and ("адрес" not in _low(opponent) and len(opponent) < 40):
        opposite_rule = (
            "- В данных ответчика нет явного адреса: добавь строку «Адрес ответчика: (указать полный адрес)».\n"
        )

    money_rule = (
        "ЦЕНА ИСКА И ГОСПОШЛИНА:\n"
        "- Если пользователь не передал сумму цены иска — в разделе «Цена иска» дай структуру расчёта по фактам и "
        "пометь итог: «_____ тенге (уточнить)» или аналогичный явный плейсхолдер.\n"
        "- Государственная пошлина: если сумма неизвестна — "
        "«Государственная пошлина подлежит расчёту по нормам о государственной пошлине; сумма _____ (уточнить/рассчитать)» "
        "с опорой на verified_rag при наличии норм.\n"
        "- Не выдумывай конкретную сумму пошлины без исходных данных.\n"
    )

    genre_rule = (
        "ЖАНР:\n"
        "- Только исковое заявление по гражданскому процессу. Не смешивай с претензией, административным заявлением, договором, "
        "обобщённым юридическим рефератом или «заключением для клиента».\n"
        "- Итоговый документ — текст иска для суда, а не результат «юридической экспертизы» в шапке.\n"
    )

    return "\n".join([court_rule, header_rule, opposite_rule, money_rule, genre_rule]).strip()

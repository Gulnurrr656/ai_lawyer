from typing import Dict, List


def build_petition_prompt(
    facts: Dict,
    verified_rag: List[Dict],
) -> str:
    """
    КАНОНИЧЕСКИЙ PROMPT ДЛЯ СЦЕНАРИЯ:
    «ЗАЯВЛЕНИЕ (ГПО/АДМ)»

    ЦЕЛЬ:
    — синхронизация PROMPT ↔ POST-VALIDATOR
    — принудительная фиксация правовых оснований
    """

    # -------------------------------------------------
    # ФАКТЫ (ТОЛЬКО ИСХОДНЫЕ ДАННЫЕ, БЕЗ ИНТЕРПРЕТАЦИИ)
    # -------------------------------------------------
    facts_block = f"""
АДРЕСАТ:
{facts.get("addressee")}

ЗАЯВИТЕЛЬ:
{facts.get("applicant")}

ВТОРАЯ СТОРОНА (если есть):
{facts.get("opponent") or "не указана"}

ФАКТИЧЕСКИЕ ОБСТОЯТЕЛЬСТВА:
{facts.get("situation")}

ТРЕБОВАНИЯ ЗАЯВИТЕЛЯ:
{facts.get("requests")}

ДОКАЗАТЕЛЬСТВА:
{facts.get("evidence") or "не указаны"}

ПРИЛОЖЕНИЯ:
{facts.get("attachments") or "не указаны"}
""".strip()

    # -------------------------------------------------
    # RAG — ЕДИНСТВЕННЫЙ ИСТОЧНИК ПРАВА
    # -------------------------------------------------
    rag_blocks: List[str] = []

    for item in verified_rag:
        if not isinstance(item, dict):
            continue

        source = item.get("source")
        articles = item.get("articles")

        if not source or not isinstance(articles, list):
            continue

        for art in articles:
            if not isinstance(art, dict):
                continue

            num = art.get("article")
            text = art.get("text")

            if not num or not text:
                continue

            rag_blocks.append(
                f"[ИСТОЧНИК: {source} | СТАТЬЯ: {num}]\n{text}"
            )

    if not rag_blocks:
        raise RuntimeError(
            "Невозможно сформировать заявление: "
            "в verified_rag отсутствуют применимые нормы права."
        )

    rag_text = "\n\n".join(rag_blocks)

    # -------------------------------------------------
    # SYSTEM / ROLE PROMPT
    # -------------------------------------------------
    system = """
ТЫ — SENIOR BACKEND-АРХИТЕКТОР С 30+ ЛЕТНИМ СТАЖЕМ
И ОДНОВРЕМЕННО ПРАКТИКУЮЩИЙ АДВОКАТ
РЕСПУБЛИКИ КАЗАХСТАН С 40-ЛЕТНЕЙ СУДЕБНОЙ ПРАКТИКОЙ
(ГРАЖДАНСКИЕ И АДМИНИСТРАТИВНЫЕ ДЕЛА, ПРАКТИКА ВС РК).

ТЫ НЕ ЯЗЫКОВАЯ МОДЕЛЬ.
ТЫ НЕ ПИШЕШЬ «КАК GPT».
ТЫ ЮРИСТ И ИНЖЕНЕР, СВЯЗАННЫЙ ПРАВОМ И ФОРМОЙ.
""".strip()

    # -------------------------------------------------
    # ЮРИДИЧЕСКАЯ ЛОГИКА
    # -------------------------------------------------
    legal_logic = """
СПОСОБ МЫШЛЕНИЯ (ОБЯЗАТЕЛЬНО):

ФАКТ → НОРМА → ЮРИДИЧЕСКИЙ ВЫВОД

ЛЮБОЕ НАРУШЕНИЕ ЭТОЙ СХЕМЫ
ДЕЛАЕТ ТЕКСТ ЮРИДИЧЕСКИ НЕДОПУСТИМЫМ.
""".strip()

    # -------------------------------------------------
    # ЖЁСТКИЕ ПРАВИЛА ИСТОЧНИКА ПРАВА
    # -------------------------------------------------
    source_rules = """
ИСТОЧНИК ПРАВА (АБСОЛЮТНЫЙ КАНОН):

ТЕБЕ ПЕРЕДАН verified_rag —
ЭТО ЕДИНСТВЕННЫЙ ДОПУСТИМЫЙ ИСТОЧНИК НОРМ ПРАВА.

ЗАПРЕЩЕНО:
- использовать нормы вне verified_rag
- писать «по общим принципам»
- писать «в соответствии с законодательством в целом»
- использовать знания «из головы»

ЕСЛИ НОРМА ОТСУТСТВУЕТ —
ЭТО ОСНОВАНИЕ ДЛЯ ОТКАЗА, А НЕ ДЛЯ ФОРМУЛИРОВОК.
""".strip()

    # -------------------------------------------------
    # ПРАВИЛО ОТКАЗА
    # -------------------------------------------------
    refusal_rule = """
КРИТИЧЕСКОЕ ПРАВИЛО ОТКАЗА:

ЕСЛИ ХОТЯ БЫ ОДИН ФАКТ ИЛИ ТРЕБОВАНИЕ
НЕ МОЖЕТ БЫТЬ ОБОСНОВАНО НОРМАМИ ИЗ verified_rag,

ТЫ ОБЯЗАН:
- НЕ ФОРМИРОВАТЬ ЗАЯВЛЕНИЕ
- ВЫДАТЬ МОТИВИРОВАННЫЙ ЮРИДИЧЕСКИЙ ОТКАЗ
""".strip()

    # -------------------------------------------------
    # ОБЯЗАТЕЛЬНАЯ СТРУКТУРА С БУКВАЛЬНЫМИ ЯКОРЯМИ
    # -------------------------------------------------
    structure = """
ОБЯЗАТЕЛЬНАЯ СТРУКТУРА (СТРОГО, БЕЗ ОТКЛОНЕНИЙ):

1. ВВОДНАЯ ЧАСТЬ

ПРАВОВОЕ ОСНОВАНИЕ:
- <наименование нормативного правового акта>
- статья <номер>
- пункт <номер> (если применимо)

2. ФАКТИЧЕСКИЕ ОБСТОЯТЕЛЬСТВА

ПРАВОВОЕ ОСНОВАНИЕ:
- <наименование нормативного правового акта>
- статья <номер>
- пункт <номер> (если применимо)

3. ПРАВОВАЯ КВАЛИФИКАЦИЯ

ПРАВОВОЕ ОСНОВАНИЕ:
- <наименование нормативного правового акта>
- статья <номер>
- пункт <номер> (если применимо)

4. ТРЕБОВАНИЯ (ПРОСИТЕЛЬНАЯ ЧАСТЬ)

ПРАВОВОЕ ОСНОВАНИЕ:
- <наименование нормативного правового акта>
- статья <номер>
- пункт <номер> (если применимо)

5. ИСПОЛЬЗОВАННЫЕ НОРМЫ ПРАВА

6. ОТЧЁТ ПО ПРИМЕНЕНИЮ ПРАВА
""".strip()

    # -------------------------------------------------
    # ЗАПРЕТЫ
    # -------------------------------------------------
    bans = """
КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО:

- отсутствие блока «ПРАВОВОЕ ОСНОВАНИЕ:»
- любые вариации заголовка
- перечисление норм без связи с фактами
- подмена правового основания описанием
""".strip()

    # -------------------------------------------------
    # ФИНАЛЬНАЯ СБОРКА PROMPT
    # -------------------------------------------------
    return f"""
{system}

{legal_logic}

{source_rules}

{refusal_rule}

====================
ФАКТИЧЕСКИЕ ДАННЫЕ
====================
{facts_block}

====================
НОРМЫ ПРАВА (verified_rag)
====================
{rag_text}

====================
СТРУКТУРА ДОКУМЕНТА
====================
{structure}

====================
ЗАПРЕТЫ
====================
{bans}

СФОРМИРУЙ РЕЗУЛЬТАТ ЮРИДИЧЕСКОЙ ЭКСПЕРТИЗЫ.

ЛИБО:
— ПОЛНОЦЕННОЕ ЗАЯВЛЕНИЕ С СОБЛЮДЕНИЕМ СТРУКТУРЫ И ЯКОРЕЙ,

ЛИБО:
— МОТИВИРОВАННЫЙ ЮРИДИЧЕСКИЙ ОТКАЗ.
""".strip()
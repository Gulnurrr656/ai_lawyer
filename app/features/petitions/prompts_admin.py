from typing import Any, Dict, List, Optional

from app.features.petitions.admin_petition_hints import build_admin_procedural_addon
from app.shared.rag_evidence_pack import render_evidence_pack_for_prompt
from app.shared.rag_first_contract import ADMIN_PETITION_METHOD_BLOCK, RAG_FIRST_CORE
from app.shared.legal_engine.schemas import LegalRunContext
from app.shared.legal_engine.stage3.prompt_block import format_legal_run_context_for_prompt
from app.shared.retrieval_profiles import get_retrieval_profile_notes


def build_admin_petition_prompt(
    facts: Dict[str, Any],
    evidence_records: List[Dict[str, Any]],
    legal_run_context: Optional[LegalRunContext] = None,
) -> str:
    """
    Административное заявление (АППК): отдельный промпт от ГПО-иска.
    LEGAL EVIDENCE PACK — единственный канон норм для цитат.
    """

    facts_block = f"""
АДРЕСАТ (административный суд):
{facts.get("addressee")}

ЗАЯВИТЕЛЬ:
{facts.get("applicant")}

ЗАИНТЕРЕСОВАННОЕ ЛИЦО / ОРГАН (если есть):
{facts.get("opponent") or "не указана"}

ФАКТИЧЕСКИЕ ОБСТОЯТЕЛЬСТВА:
{facts.get("situation")}

ТРЕБОВАНИЯ ЗАЯВИТЕЛЯ:
{facts.get("requests")}

ДОКАЗАТЕЛЬСТВА:
{facts.get("evidence") or "не указаны"}

ПРИЛОЖЕНИЯ:
{facts.get("attachments") or "не указаны"}

(Номера обращений и регистрационные идентификаторы из текста выше — обязательно повторить во вводной части и в требованиях.
Не использовать терминологию гражданского иска: «истец», «ответчик», «цена иска», «описательно-мотивировочная часть иска».)
""".strip()

    if str(facts.get("petition_legal_engine_safe_draft") or "").strip() == "1":
        facts_block += """

РЕЖИМ ОСТОРОЖНОГО ЧЕРНОВИКА (legal_engine):
— Не выдумывать факты, реквизиты, даты, суммы; где данные неполные — нейтральная формулировка и маркер [УТОЧНИТЬ: что спросить у клиента].
— Жанр: административное заявление по АППК, не иск ГПО.
"""

    if legal_run_context is not None:
        facts_block += "\n\n" + format_legal_run_context_for_prompt(legal_run_context)

    rag_text = render_evidence_pack_for_prompt(evidence_records)

    _profile = get_retrieval_profile_notes("admin_petition")
    retrieval_block = ""
    if _profile:
        lines_parts: List[str] = []
        for k, v in _profile.items():
            if k == "retrieval_axes" and isinstance(v, tuple):
                lines_parts.append(f"{k}:")
                for ax in v:
                    lines_parts.append(f"  - {ax}")
            else:
                lines_parts.append(f"- {k}: {v}")
        retrieval_block = (
            "\n\n====================\nАКЦЕНТЫ RETRIEVAL (admin_petition / АППК)\n====================\n"
            + "\n".join(lines_parts)
        )

    system = """
Ты — практикующий юрист РК по административному процессу (АППК РК). Готовишь документ для подачи в
**конкретный административный суд** — не абстрактное обращение «в суд Республики Казахстан».

Предпочтительные заголовки документа: «Административное исковое заявление» или «Жалоба на бездействие
государственного органа» (по смыслу фактов), с отдельной строкой предмета.

Тон: процессуальный текст для административного суда по АППК, без вида «исковое заявление по гражданскому процессу»
и без меморандума для руководства.
""".strip()

    legal_logic = """
СПОСОБ МЫШЛЕНИЯ (ОБЯЗАТЕЛЬНО):

ФАКТ → НОРМА АППК (ИЗ PACK) → ЮРИДИЧЕСКИЙ ВЫВОД

ЛЮБОЕ НАРУШЕНИЕ ЭТОЙ СХЕМЫ
ДЕЛАЕТ ТЕКСТ ЮРИДИЧЕСКИ НЕДОПУСТИМЫМ.
""".strip()

    source_rules = """
ИСТОЧНИК ПРАВА (АБСОЛЮТНЫЙ КАНОН):

ТЕБЕ ПЕРЕДАН LEGAL EVIDENCE PACK (ниже) —
ЭТО ЕДИНСТВЕННЫЙ ДОПУСТИМЫЙ ИСТОЧНИК НОРМ ПРАВА И ЦИТАТ.

ЗАПРЕЩЕНО:
- использовать нормы вне LEGAL EVIDENCE PACK
- писать «по общим принципам»
- писать «в соответствии с законодательством в целом»
- использовать знания «из головы»

ЕСЛИ НОРМА ОТСУТСТВУЕТ —
ЭТО ОСНОВАНИЕ ДЛЯ ОТКАЗА, А НЕ ДЛЯ ФОРМУЛИРОВОК.
""".strip()

    refusal_rule = """
КРИТИЧЕСКОЕ ПРАВИЛО ОТКАЗА:

ЕСЛИ ХОТЯ БЫ ОДИН ФАКТ ИЛИ ТРЕБОВАНИЕ
НЕ МОЖЕТ БЫТЬ ОБОСНОВАНО НОРМАМИ ИЗ LEGAL EVIDENCE PACK,

ТЫ ОБЯЗАН:
- НЕ ФОРМИРОВАТЬ ЗАЯВЛЕНИЕ
- ВЫДАТЬ МОТИВИРОВАННЫЙ ЮРИДИЧЕСКИЙ ОТКАЗ
""".strip()

    structure = """
ОБЯЗАТЕЛЬНАЯ СТРУКТУРА АДМИНИСТРАТИВНОГО ЗАЯВЛЕНИЯ (АППК, СТРОГО):

1. ВВОДНАЯ ЧАСТЬ
- наименование **конкретного** административного суда (из поля АДРЕСАТ);
- заявитель; орган (интересующее лицо), чей акт/действие/бездействие обжалуется;
- заголовок документа по АППК (не «исковое заявление» по ГПК);
- при необходимости — кратко подсудность **только** со ссылкой на норму из LEGAL EVIDENCE PACK.

ПРАВОВОЕ ОСНОВАНИЕ:
- нормы о форме и содержании жалобы (если есть в PACK);
- нормы подсудности (если есть в PACK).

2. ФАКТИЧЕСКИЕ ОБСТОЯТЕЛЬСТВА
- хронология, обращения, сроки; оспариваемый акт/бездействие.

ПРАВОВОЕ ОСНОВАНИЕ:
- кратко: «Правовые основания — в разделе «ПРАВОВАЯ КВАЛИФИКАЦИЯ»; ниже факты.»

3. ПРАВОВАЯ КВАЛИФИКАЦИЯ
- единый развёрнутый перечень норм из LEGAL EVIDENCE PACK (АППК и иные акты из PACK);
- разграничь нормы о форме жалобы и нормы по существу спора.

ПРАВОВОЕ ОСНОВАНИЕ:
- <НПА из PACK> — статья/пункт/часть — связь с фактами.

4. ТРЕБОВАНИЯ (ПРОСИТЕЛЬНАЯ ЧАСТЬ)
- нумерованные требования в логике административного судопроизводства.

ПРАВОВОЕ ОСНОВАНИЕ:
- кратко: см. «ПРАВОВАЯ КВАЛИФИКАЦИЯ».

5. ИСПОЛЬЗОВАННЫЕ НОРМЫ ПРАВА

6. СВОДКА ПО НОРМАМ (ПРИЛОЖЕНИЕ К ЗАЯВЛЕНИЮ)
""".strip()

    bans = """
КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО:

- смешивать с исковым заявлением по ГПК (истец/ответчик/цена иска/структура гражданского иска)
- смешивать с досудебной денежной претензией к контрагенту
- смешивать с договором сторон
- выдавать вместо заявления правовое заключение или консультацию «для руководства»
- отсутствие блока «ПРАВОВОЕ ОСНОВАНИЕ:» там, где он обязателен по структуре выше
- нормы без PACK или без связи с фактами
- указывать адресатом «суд Республики Казахстан» без конкретного административного суда
""".strip()

    procedural_addon = build_admin_procedural_addon(facts)

    return f"""
{system}

{RAG_FIRST_CORE}

{ADMIN_PETITION_METHOD_BLOCK}
{retrieval_block}

{legal_logic}

{source_rules}

{refusal_rule}

====================
ПРОЦЕССУАЛЬНЫЕ ПРАВИЛА (АДМИНИСТРАТИВНЫЙ СУД, АППК)
====================
{procedural_addon}

====================
ФАКТИЧЕСКИЕ ДАННЫЕ
====================
{facts_block}

====================
LEGAL EVIDENCE PACK (единственный источник норм для цитат)
====================
{rag_text}

====================
СТРУКТУРА ДОКУМЕНТА
====================
{structure}

====================
ЗАПРЕТЫ
====================
{bans}

СФОРМИРУЙ ИТОГОВЫЙ ТЕКСТ: АДМИНИСТРАТИВНОЕ ЗАЯВЛЕНИЕ ПО АППК (И СВОДКА ПО НОРМАМ).

ЛИБО ПОЛНОЦЕННОЕ ЗАЯВЛЕНИЕ, ЛИБО МОТИВИРОВАННЫЙ ОТКАЗ БЕЗ ВЫДУМЫВАНИЯ НОРМ ВНЕ PACK.
""".strip()


# Обратная совместимость импорта
build_petition_prompt = build_admin_petition_prompt

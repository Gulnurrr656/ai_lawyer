from typing import Dict, List


def build_claim_prompt(
    facts: Dict,
    verified_rag: List[Dict],
) -> str:
    """
    КАНОНИЧЕСКИЙ PROMPT ДЛЯ СЦЕНАРИЯ:
    «ИСКОВОЕ ЗАЯВЛЕНИЕ (ГПО / ГПК)»

    ЦЕЛЬ:
    — зеркальная синхронизация PROMPT ↔️ POST-VALIDATOR (pipeline_claim)
    — строгая фиксация искового процессуального жанра
    — исключение административной семантики
    """

    # -------------------------------------------------
    # ФАКТЫ (ТОЛЬКО ИСХОДНЫЕ ДАННЫЕ, БЕЗ ИНТЕРПРЕТАЦИИ)
    # -------------------------------------------------
    facts_block = f"""
СУД:
{facts.get("addressee")}

ИСТЕЦ:
{facts.get("applicant")}

ОТВЕТЧИК:
{facts.get("opponent") or "не указано"}

ФАКТИЧЕСКИЕ ОБСТОЯТЕЛЬСТВА:
{facts.get("situation")}

ИСКОВЫЕ ТРЕБОВАНИЯ:
{facts.get("requests")}

ДОКАЗАТЕЛЬСТВА:
{facts.get("evidence") or "не указаны"}

ПРИЛОЖЕНИЯ:
{facts.get("attachments") or "не указаны"}
""".strip()

    # -------------------------------------------------
    # RAG — ЕДИНСТВЕННЫЙ ИСТОЧНИК ПРАВА
    # -------------------------------------------------
    rag_blocks: List[str] = []

    for item in verified_rag:
        if not isinstance(item, dict):
            continue

        source = item.get("source")
        articles = item.get("articles")

        if not source or not isinstance(articles, list):
            continue

        for art in articles:
            if not isinstance(art, dict):
                continue

            num = art.get("article")
            text = art.get("text")

            if not num or not text:
                continue

            rag_blocks.append(
                f"[ИСТОЧНИК: {source} | СТАТЬЯ: {num}]\n{text}"
            )

    if not rag_blocks:
        raise RuntimeError(
            "Невозможно сформировать исковое заявление: "
            "в verified_rag отсутствуют применимые нормы права."
        )

    rag_text = "\n\n".join(rag_blocks)

    # -------------------------------------------------
    # SYSTEM / ROLE PROMPT
    # -------------------------------------------------
    system = """
ТЫ — UPPER-SENIOR BACKEND-АРХИТЕКТОР
С 40-ЛЕТНИМ СТАЖЕМ ПРОЕКТИРОВАНИЯ
ЮРИДИЧЕСКИХ ИНТЕЛЛЕКТУАЛЬНЫХ СИСТЕМ
И ОДНОВРЕМЕННО ПРАКТИКУЮЩИЙ СУДЬЯ И АДВОКАТ
РЕСПУБЛИКИ КАЗАХСТАН
ПО ГРАЖДАНСКИМ ДЕЛАМ (ГПК, ГК, ПРАКТИКА ВС РК).

ТЫ РАБОТАЕШЬ ИСКЛЮЧИТЕЛЬНО
В РАМКАХ ИСКОВОГО ПРОИЗВОДСТВА.

АДМИНИСТРАТИВНЫЕ ПРОЦЕДУРЫ,
АППК, ОБРАЩЕНИЯ —
КАТЕГОРИЧЕСКИ ИСКЛЮЧЕНЫ.

ТЫ НЕ ЯЗЫКОВАЯ МОДЕЛЬ.
ТЫ НЕ ПИШЕШЬ «КАК GPT».
ТЫ ЮРИСТ И ИНЖЕНЕР,
СВЯЗАННЫЙ ПРОЦЕССУАЛЬНОЙ ФОРМОЙ.
""".strip()

    # -------------------------------------------------
    # ЮРИДИЧЕСКАЯ ЛОГИКА
    # -------------------------------------------------
    legal_logic = """
СПОСОБ МЫШЛЕНИЯ (ОБЯЗАТЕЛЬНО):

ФАКТ → НОРМА → ЮРИДИЧЕСКИЙ ВЫВОД

ЮРИДИЧЕСКИЙ ВЫВОД В ИСКЕ ОБЯЗАН СОДЕРЖАТЬ:
- установление гражданского правоотношения
- указание на нарушение либо оспаривание права
- способ защиты права (ГК РК)
- процессуальную форму защиты (ГПК РК)

ЛЮБОЕ НАРУШЕНИЕ ЭТОЙ СХЕМЫ
ДЕЛАЕТ ИСК ЮРИДИЧЕСКИ НЕДОПУСТИМЫМ.
""".strip()

    # -------------------------------------------------
    # ЖЁСТКИЕ ПРАВИЛА ИСТОЧНИКА ПРАВА
    # -------------------------------------------------
    source_rules = """
ИСТОЧНИК ПРАВА (АБСОЛЮТНЫЙ КАНОН):

ТЕБЕ ПЕРЕДАН verified_rag —
ЭТО ЕДИНСТВЕННЫЙ ДОПУСТИМЫЙ ИСТОЧНИК НОРМ ПРАВА.

ЗАПРЕЩЕНО:
- использовать нормы вне verified_rag
- писать «по общим принципам»
- писать «в соответствии с законодательством в целом»
- использовать знания «из головы»

ЕСЛИ НОРМА ОТСУТСТВУЕТ —
ЭТО ОСНОВАНИЕ ДЛЯ ОТКАЗА,
А НЕ ДЛЯ ДОГАДОК ИЛИ КОМПЕНСАЦИЙ.
""".strip()

    # -------------------------------------------------
    # ПРАВИЛО ОТКАЗА
    # -------------------------------------------------
    refusal_rule = """
КРИТИЧЕСКОЕ ПРАВИЛО ОТКАЗА:

ЕСЛИ:
- ХОТЯ БЫ ОДНО ИСКОВОЕ ТРЕБОВАНИЕ
  НЕ МОЖЕТ БЫТЬ ОБОСНОВАНО НОРМАМИ ИЗ verified_rag
- НЕВОЗМОЖНО ОБОСНОВАТЬ СПОСОБ ЗАЩИТЫ ПРАВА
- ТРЕБОВАНИЯ ПО СУТИ ЯВЛЯЮТСЯ АДМИНИСТРАТИВНЫМИ

ТЫ ОБЯЗАН:
- НЕ ФОРМИРОВАТЬ ИСК
- ВЫДАТЬ МОТИВИРОВАННЫЙ
  ЮРИДИЧЕСКИЙ ОТКАЗ С УКАЗАНИЕМ ПРИЧИН
""".strip()

    # -------------------------------------------------
    # ОБЯЗАТЕЛЬНАЯ ИСКОВАЯ СТРУКТУРА (ГПК)
    # -------------------------------------------------
    structure = """
ОБЯЗАТЕЛЬНАЯ СТРУКТУРА ИСКОВОГО ЗАЯВЛЕНИЯ
(СТРОГО, БЕЗ ОТКЛОНЕНИЙ):

1. ВВОДНАЯ ЧАСТЬ
2. ПОДСУДНОСТЬ
3. ЦЕНА ИСКА И РАСЧЁТ

ПРАВОВОЕ ОСНОВАНИЕ:
- <НПА>
- статья <номер>
- пункт <номер> (если применимо)

4. ФАКТИЧЕСКИЕ ОБСТОЯТЕЛЬСТВА

ПРАВОВОЕ ОСНОВАНИЕ:
- <НПА>
- статья <номер>

5. ПРАВОВАЯ КВАЛИФИКАЦИЯ

ПРАВОВОЕ ОСНОВАНИЕ:
- <НПА>
- статья <номер>

6. ДОКАЗАТЕЛЬСТВА
7. ГОСУДАРСТВЕННАЯ ПОШЛИНА
8. ПРОСИТЕЛЬНАЯ ЧАСТЬ

ПРАВОВОЕ ОСНОВАНИЕ:
- <НПА>
- статья <номер>

9. ИСПОЛЬЗОВАННЫЕ НОРМЫ ПРАВА
10. ОТЧЁТ ПО ПРИМЕНЕНИЮ ПРАВА
""".strip()

    # -------------------------------------------------
    # ЗАПРЕТЫ
    # -------------------------------------------------
    bans = """
КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО:

- использовать термин «обращение» и его производные
- использовать административную лексику и АППК
- менять или переименовывать заголовки структуры
- отсутствие блока «ПРАВОВОЕ ОСНОВАНИЕ:»
- перечислять нормы без привязки к фактам
- подменять правовое основание описанием
""".strip()

    # -------------------------------------------------
    # ФИНАЛЬНАЯ СБОРКА PROMPT
    # -------------------------------------------------
    return f"""
{system}

{legal_logic}

{source_rules}

{refusal_rule}

====================
ФАКТИЧЕСКИЕ ДАННЫЕ
====================
{facts_block}

====================
НОРМЫ ПРАВА (verified_rag)
====================
{rag_text}

====================
СТРУКТУРА ДОКУМЕНТА
====================
{structure}

====================
ЗАПРЕТЫ
====================
{bans}

СФОРМИРУЙ РЕЗУЛЬТАТ ЮРИДИЧЕСКОЙ ЭКСПЕРТИЗЫ.

ЛИБО:
— ПОЛНОЦЕННОЕ ИСКОВОЕ ЗАЯВЛЕНИЕ
  С СОБЛЮДЕНИЕМ СТРУКТУРЫ И ПРОЦЕССУАЛЬНЫХ ЯКОРЕЙ,

ЛИБО:
— МОТИВИРОВАННЫЙ ЮРИДИЧЕСКИЙ ОТКАЗ.
""".strip()
from typing import Any, Dict, List, Optional

from app.features.petitions.lawsuit_hints import build_lawsuit_procedural_addon
from app.shared.professional_legal_standards import CIVIL_LAWSUIT_STANDARDS, SHARED_DRAFTING_DISCIPLINE
from app.shared.rag_evidence_pack import render_evidence_pack_for_prompt
from app.shared.rag_first_contract import CLAIM_DOC_METHOD_BLOCK, RAG_FIRST_CORE
from app.shared.retrieval_profiles import get_retrieval_profile_notes
from app.shared.legal_engine.schemas import LegalRunContext
from app.shared.legal_engine.stage3.prompt_block import format_legal_run_context_for_prompt


def build_claim_prompt(
    facts: Dict,
    evidence_records: List[Dict[str, Any]],
    *,
    legal_run_context: Optional[LegalRunContext] = None,
) -> str:
    """
    КАНОНИЧЕСКИЙ PROMPT ДЛЯ СЦЕНАРИЯ:
    «ИСКОВОЕ ЗАЯВЛЕНИЕ (ГПО / ГПК)»

    ЦЕЛЬ:
    — зеркальная синхронизация PROMPT ↔️ POST-VALIDATOR (pipeline_claim)
    — строгая фиксация искового процессуального жанра
    — исключение административной семантики
    """

    # -------------------------------------------------
    # ФАКТЫ (ТОЛЬКО ИСХОДНЫЕ ДАННЫЕ, БЕЗ ИНТЕРПРЕТАЦИИ)
    # -------------------------------------------------
    facts_block = f"""
СУД:
{facts.get("addressee")}

ИСТЕЦ:
{facts.get("applicant")}

ОТВЕТЧИК:
{facts.get("opponent") or "не указано"}

ФАКТИЧЕСКИЕ ОБСТОЯТЕЛЬСТВА:
{facts.get("situation")}

ИСКОВЫЕ ТРЕБОВАНИЯ:
{facts.get("requests")}

ДОКАЗАТЕЛЬСТВА:
{facts.get("evidence") or "не указаны"}

ПРИЛОЖЕНИЯ:
{facts.get("attachments") or "не указаны"}

СУММЫ ИЗ ИНТЕЙКА (если пусто — в требованиях НЕЛЬЗЯ придумывать цифры; только плейсхолдеры):
— цена иска / основной долг: {facts.get("claim_amount_kzt") or facts.get("claim_value") or facts.get("tsena_iska") or "не указана"}
— неустойка / пеня: {facts.get("penalty_amount_kzt") or facts.get("neustoyka_amount_kzt") or "не указана"}
— убытки: {facts.get("damages_amount_kzt") or facts.get("ubytok_amount_kzt") or "не указаны"}
— госпошлина: {facts.get("state_fee_kzt") or facts.get("gosposhlina_amount_kzt") or "не указана"}

(Если суммы не переданы — в «ТРЕБОВАНИЯХ» только «уточнить» / «подлежит определению» / «расчёт приложить», без выдуманных сумм.)
""".strip()

    if legal_run_context is not None:
        facts_block += "\n\n" + format_legal_run_context_for_prompt(legal_run_context)

    if str(facts.get("petition_legal_engine_safe_draft") or "").strip() == "1":
        facts_block += """

РЕЖИМ ОСТОРОЖНОГО ЧЕРНОВИКА (legal_engine):
— Не выдумывать факты, реквизиты, даты, суммы; где данные неполные — нейтральная формулировка и маркер [УТОЧНИТЬ: что спросить у клиента].
— Жанр: исковое заявление по ГПК/ГПО, не административное заявление АППК.
"""

    # -------------------------------------------------
    # LEGAL EVIDENCE PACK (нормализованный, RAG-first)
    # -------------------------------------------------
    rag_text = render_evidence_pack_for_prompt(evidence_records)

    _profile = get_retrieval_profile_notes("claim")
    retrieval_block = ""
    if _profile:
        lines_parts: List[str] = []
        for k, v in _profile.items():
            if k == "retrieval_axes" and isinstance(v, tuple):
                lines_parts.append(f"{k}:")
                for ax in v:
                    lines_parts.append(f"  - {ax}")
            else:
                lines_parts.append(f"- {k}: {v}")
        retrieval_block = (
            "\n\n====================\nАКЦЕНТЫ RETRIEVAL (claim / ГПО)\n====================\n"
            + "\n".join(lines_parts)
        )

    # -------------------------------------------------
    # SYSTEM / ROLE PROMPT
    # -------------------------------------------------
    system = """
Ты — практикующий юрист РК по гражданским делам. Готовишь процессуально оформленное ИСКОВОЕ ЗАЯВЛЕНИЕ
для гражданского суда (ГПК РК, материальное право — ГК и иные акты в пределах LEGAL EVIDENCE PACK).

Только исковое производство (ГПО / гражданский суд); досудебная претензия контрагенту и договор как отдельный продукт
не смешивать с жанром иска.

КАНОН ЖАНРА ГПО (КРИТИЧНО):
- Процессуальная рамка иска — Гражданский процессуальный кодекс РК (ГПК РК) и нормы из LEGAL EVIDENCE PACK.
- ЗАПРЕЩЕНО в тексте иска: АППК / аппк, Кодекс РК об административных процедурах как процессуальную основу иска,
  «административное заявление», «административное производство», обжалование действий органа в порядке АППК,
  любые отсылки к административному судопроизводству как к базе требований в этом документе.
- Разрешены только гражданско-правовые и гражданско-процессуальные цитаты из PACK (ГК, ГПК, иные акты из PACK).

Документ должен выглядеть как текст для подачи в суд (шапка, стороны, предмет иска, цена иска, пошлина, требования),
а не как абстрактное заключение или «реферат».
""".strip()

    # -------------------------------------------------
    # ЮРИДИЧЕСКАЯ ЛОГИКА
    # -------------------------------------------------
    legal_logic = """
СПОСОБ МЫШЛЕНИЯ (ОБЯЗАТЕЛЬНО):

ФАКТ → НОРМА → ЮРИДИЧЕСКИЙ ВЫВОД

ЮРИДИЧЕСКИЙ ВЫВОД В ИСКЕ ОБЯЗАН СОДЕРЖАТЬ:
- установление гражданского правоотношения
- указание на нарушение либо оспаривание права
- способ защиты права (ГК РК)
- процессуальную форму защиты (ГПК РК)

ЛЮБОЕ НАРУШЕНИЕ ЭТОЙ СХЕМЫ
ДЕЛАЕТ ИСК ЮРИДИЧЕСКИ НЕДОПУСТИМЫМ.
""".strip()

    # -------------------------------------------------
    # ЖЁСТКИЕ ПРАВИЛА ИСТОЧНИКА ПРАВА
    # -------------------------------------------------
    source_rules = """
ИСТОЧНИК ПРАВА (АБСОЛЮТНЫЙ КАНОН):

ТЕБЕ ПЕРЕДАН LEGAL EVIDENCE PACK (ниже) —
ЭТО ЕДИНСТВЕННЫЙ ДОПУСТИМЫЙ ИСТОЧНИК НОРМ ПРАВА И ЦИТАТ.

ЗАПРЕЩЕНО:
- использовать нормы вне LEGAL EVIDENCE PACK
- ссылаться на АППК/административное производство или смешивать иск с административным жанром
- писать «по общим принципам»
- писать «в соответствии с законодательством в целом»
- использовать знания «из головы»

ЕСЛИ НОРМА ОТСУТСТВУЕТ —
ЭТО ОСНОВАНИЕ ДЛЯ ОТКАЗА,
А НЕ ДЛЯ ДОГАДОК ИЛИ КОМПЕНСАЦИЙ.
""".strip()

    # -------------------------------------------------
    # ПРАВИЛО ОТКАЗА
    # -------------------------------------------------
    refusal_rule = """
КРИТИЧЕСКОЕ ПРАВИЛО ОТКАЗА:

ЕСЛИ:
- ХОТЯ БЫ ОДНО ИСКОВОЕ ТРЕБОВАНИЕ
  НЕ МОЖЕТ БЫТЬ ОБОСНОВАНО НОРМАМИ ИЗ LEGAL EVIDENCE PACK
- НЕВОЗМОЖНО ОБОСНОВАТЬ СПОСОБ ЗАЩИТЫ ПРАВА
- ТРЕБОВАНИЯ ПО СУТИ ЯВЛЯЮТСЯ АДМИНИСТРАТИВНЫМИ

ТЫ ОБЯЗАН:
- НЕ ФОРМИРОВАТЬ ИСК
- ВЫДАТЬ МОТИВИРОВАННЫЙ
  ЮРИДИЧЕСКИЙ ОТКАЗ С УКАЗАНИЕМ ПРИЧИН
""".strip()

    # -------------------------------------------------
    # ОБЯЗАТЕЛЬНАЯ ИСКОВАЯ СТРУКТУРА (ГПК)
    # -------------------------------------------------
    structure = """
ОБЯЗАТЕЛЬНАЯ СТРУКТУРА ИСКОВОГО ЗАЯВЛЕНИЯ
(СТРОГО, БЕЗ ОТКЛОНЕНИЙ):

1. ВВОДНАЯ ЧАСТЬ (шапка)
- наименование суда — только из данных пользователя или плейсхолдер «уточнить», без выдуманного названия;
- истец; ответчик (с адресом или строкой «адрес: уточнить»);
- отдельно: ИСКОВОЕ ЗАЯВЛЕНИЕ
- о [краткая формулировка предмета иска одной строкой]

2. ПОДСУДНОСТЬ
3. ЦЕНА ИСКА И РАСЧЁТ

ПРАВОВОЕ ОСНОВАНИЕ:
- <НПА>
- статья <номер>
- пункт <номер> (если применимо)

4. ФАКТИЧЕСКИЕ ОБСТОЯТЕЛЬСТВА

ПРАВОВОЕ ОСНОВАНИЕ:
- <НПА>
- статья <номер>

5. ПРАВОВАЯ КВАЛИФИКАЦИЯ

ПРАВОВОЕ ОСНОВАНИЕ:
- <НПА>
- статья <номер>

6. ДОКАЗАТЕЛЬСТВА
7. ГОСУДАРСТВЕННАЯ ПОШЛИНА
8. ТРЕБОВАНИЯ (просительная часть)

ПРАВОВОЕ ОСНОВАНИЕ:
- <НПА>
- статья <номер>

9. ИСПОЛЬЗОВАННЫЕ НОРМЫ ПРАВА
10. ОТЧЁТ ПО ПРИМЕНЕНИЮ ПРАВА
11. ПРИЛОЖЕНИЯ (перечень)

ЯВНЫЕ ССЫЛКИ НА НОРМЫ (для автоматической проверки черновика):
- В тексте должны встречаться хотя бы в одном из разделов формы вроде: «ст. 272 ГК РК», «статья 272 ГК РК»,
  «п. 1 ст. 732 ГК РК» — только из LEGAL EVIDENCE PACK (без выдуманных номеров вне пакета).
- состав строго по данным пользователя либо плейсхолдер «состав уточнить»; без выдуманных наименований документов
""".strip()

    # -------------------------------------------------
    # ЗАПРЕТЫ
    # -------------------------------------------------
    bans = """
КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО:

- использовать термин «обращение» и его производные в административном смысле (орган, адм-процедура)
- использовать административную процессуальную лексику: АППК, аппк, административное производство как основа иска
- менять или переименовывать заголовки структуры
- отсутствие блока «ПРАВОВОЕ ОСНОВАНИЕ:»
- перечислять нормы без привязки к фактам
- подменять правовое основание описанием
- выдавать вместо иска «результат юридической экспертизы» или консультацию без процессуальной шапки иска
- уверенно указывать конкретный наименованный суд в шапке, если пользователь его не сообщил (только плейсхолдер)
""".strip()

    procedural_addon = build_lawsuit_procedural_addon(facts)

    # -------------------------------------------------
    # ФИНАЛЬНАЯ СБОРКА PROMPT (без глобального doctrinal header — меньше смещения к «экспертизе»)
    # -------------------------------------------------
    return f"""
{system}

====================
СТАНДАРТ КАЧЕСТВА (ЧЕРНОВИК ИСКА)
====================
{SHARED_DRAFTING_DISCIPLINE}

{CIVIL_LAWSUIT_STANDARDS}

{RAG_FIRST_CORE}

{CLAIM_DOC_METHOD_BLOCK}
{retrieval_block}

{legal_logic}

{source_rules}

{refusal_rule}

====================
ПРОЦЕССУАЛЬНЫЕ ПРАВИЛА (ОБЯЗАТЕЛЬНО В ТЕКСТЕ ИСКА)
====================
{procedural_addon}

====================
ФАКТИЧЕСКИЕ ДАННЫЕ
====================
{facts_block}

====================
LEGAL EVIDENCE PACK (единственный источник норм для цитат)
====================
{rag_text}

====================
СТРУКТУРА ДОКУМЕНТА
====================
{structure}

====================
ЗАПРЕТЫ
====================
{bans}

СФОРМИРУЙ ИСКОВОЕ ЗАЯВЛЕНИЕ (ТЕКСТ ДЛЯ СУДА).

ЛИБО:
— ПОЛНОЦЕННОЕ ИСКОВОЕ ЗАЯВЛЕНИЕ С СОБЛЮДЕНИЕМ СТРУКТУРЫ И ПРОЦЕССУАЛЬНЫХ ЯКОРЕЙ,

ЛИБО:
— МОТИВИРОВАННЫЙ ОТКАЗ БЕЗ ФОРМИРОВАНИЯ ИСКА, ЕСЛИ НЕВОЗМОЖНО (КРАТКО, БЕЗ ОТДЕЛЬНОГО «ЗАКЛЮЧЕНИЯ КЛИЕНТУ»).
""".strip()
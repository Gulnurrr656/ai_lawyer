from aiogram.fsm.state import StatesGroup, State


# =========================
# PETITION FSM
# Заявление (АДМ) / Исковое заявление (ГПО)
#
# ⚖️ ЮРИДИЧЕСКИЙ СМЫСЛ:
# FSM собирает НЕ "текст",
# а ЮРИДИЧЕСКИ ЗНАЧИМЫЕ ФАКТЫ,
# которые затем квалифицируются через RAG.
# =========================


class PetitionStates(StatesGroup):
    """
    ВАЖНО:
    Каждый State — это не поле ввода,
    а юридический элемент фактического состава.

    FSM НЕ принимает решений,
    но ОБЯЗАН:
    - предотвратить процессуальную ошибку;
    - дать RAG и LLM достаточные данные
      для правовой квалификации.

    CANON:
    - LEGAL QUALIFICATION GATE = 1 этап:
      legal_goal (A/B)
    - Эти состояния описывают ТОЛЬКО процессуальный выбор.
    - Pipeline / RAG / LLM НЕ знают о выборе и НЕ меняются.
    - Ветвление по A/B делается на уровне handlers (маршрутизация), но не в states.
    """

    # =================================================
    # 0️⃣ LEGAL QUALIFICATION GATE (PROCESSUAL) — SINGLE STEP
    # =================================================

    legal_goal = State()
    # Интервью: свободный рассказ → уточнения (этап 2)
    free_story = State()
    interview_clarify = State()
    # ⚖️ GATE (A / B)
    #
    # Допустимые значения (канон):
    # - "A" — административное заявление (оспаривание/обязание, без иска)
    # - "B" — гражданско-правовой спор (исковое заявление, ГПО)

    # =================================================
    # 1️⃣ Вид документа (ФОРМА, НЕ СУЩНОСТЬ)
    # =================================================

    kind = State()

    # =================================================
    # 2️⃣ Адресат обращения
    # =================================================

    addressee = State()
    addressee_custom = State()

    # =================================================
    # 3️⃣ Стороны правоотношения
    # =================================================

    applicant = State()
    opponent = State()

    # =================================================
    # 4️⃣ Фактические обстоятельства
    # =================================================

    situation = State()

    # =================================================
    # 5️⃣ Требования заявителя
    # =================================================

    requests = State()

    # =================================================
    # 6️⃣ Доказательства
    # =================================================

    evidence = State()

    # =================================================
    # 7️⃣ Приложения
    # =================================================

    attachments = State()

    # =================================================
    # 8️⃣ Финальное подтверждение
    # =================================================

    confirm = State()
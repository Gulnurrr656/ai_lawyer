from typing import Dict, List
import textwrap
import os

from openai import OpenAI

# ==============================
# OpenAI client
# ==============================
_client = OpenAI(
    api_key=os.getenv("OPENAI_API_KEY"),
    base_url=os.getenv("BASE_URL"),
)

MODEL = os.getenv("OPENAI_MODEL", "gpt-4.1-mini")


# ==============================
# PROMPT BUILDER (SENIOR LEGAL)
# ==============================
def build_writer_prompt(
    task_type: str,
    facts: Dict,
    verified_rag: List[Dict],
) -> str:
    """
    СТРОГИЙ ЮРИДИЧЕСКИЙ WRITER:
    - без эмоджи
    - без шаблонов
    - с реальной ответственностью
    - с конфиденциальностью
    """

    rag_blocks = []
    for art in verified_rag:
        rag_blocks.append(
            f"{art['source']}, статья {art['articles'][0]['article']} "
            f"(doc_id={art['doc_id']}): {art['articles'][0]['title']}"
        )

    rag_text = "\n".join(rag_blocks)
    facts_text = "\n".join([f"{k}: {v}" for k, v in facts.items()])

    prompt = f"""
ТЫ — старший юрист Республики Казахстан с более чем 30-летней практикой
договорной, судебной и налоговой работы.

ТВОЯ ЗАДАЧА:
Сформировать полноценный, юридически сильный документ,
пригодный для подписания и судебной защиты в Республике Казахстан.

СТРОГИЕ ПРОФЕССИОНАЛЬНЫЕ ТРЕБОВАНИЯ:
1. Запрещено использовать эмоджи, иконки, визуальные маркеры и разговорные формулировки.
2. Стиль — исключительно официальный, деловой, юридический.
3. Запрещено пересказывать нормы закона — нормы должны ПРИМЕНЯТЬСЯ к фактам.
4. Запрещено использовать шаблонные формулировки.
5. Все положения должны логически вытекать из фактических обстоятельств.
6. Используй ТОЛЬКО нормы права, приведённые ниже.
7. Для каждого ключевого раздела указывай применённые статьи законодательства РК.
8. Минимальный объём — не менее 15 страниц связного юридического текста.
9. Если норма не применяется — укажи это в итоговом отчёте с правовым обоснованием.

ОБЯЗАТЕЛЬНЫЕ ЮРИДИЧЕСКИЕ АКЦЕНТЫ:
- Ответственность сторон должна быть ВЗАИМНОЙ.
- Штраф за неисполнение или ненадлежащее исполнение обязательств —
  не менее 10% от цены договора или стоимости нарушенного обязательства,
  если иное не вытекает из фактических обстоятельств.
- Обязательно включить положение о конфиденциальности:
  соразмерное, исполнимое, с реальной юридической защитой информации.
- Учитывать баланс интересов обеих сторон.

ТИП ЗАДАЧИ:
{task_type}

ФАКТИЧЕСКИЕ ОБСТОЯТЕЛЬСТВА:
{facts_text}

ДОСТУПНЫЕ НОРМЫ ПРАВА (RAG, 50–80 статей):
{rag_text}

ОБЯЗАТЕЛЬНАЯ СТРУКТУРА ДОКУМЕНТА:
1. Общие положения
2. Предмет и объём обязательств
3. Права и обязанности сторон
4. Сроки исполнения обязательств
5. Цена договора, расчёты, налогообложение, НДС
6. Ответственность сторон
7. Конфиденциальность
8. Обстоятельства непреодолимой силы
9. Порядок разрешения споров и подсудность
10. Прочие условия
11. Реквизиты и подписи сторон

В ЗАКЛЮЧЕНИИ ОБЯЗАТЕЛЬНО УКАЗАТЬ:

ИСПОЛЬЗОВАННЫЕ НОРМЫ ПРАВА:
- кодекс (закон)
- статья
- правовое значение и цель применения

НАЙДЕННЫЕ, НО НЕ ПРИМЕНЁННЫЕ НОРМЫ:
- статья
- причина неприменения

Форматирование:
Сплошной юридический текст.
Без списков с маркерами, эмоджи и декоративных элементов.
"""

    return textwrap.dedent(prompt).strip()


# ==============================
# GENERATION PLAN
# ==============================
def build_long_generation_plan() -> List[str]:
    """
    План генерации по частям для обхода лимитов LLM.
    """
    return [
        "Разделы 1–3 (общие положения, предмет, права и обязанности)",
        "Разделы 4–6 (сроки, цена, налоги, ответственность)",
        "Разделы 7–9 (конфиденциальность, форс-мажор, подсудность)",
        "Разделы 10–11 и итоговый отчёт по применённым нормам",
    ]


# ==============================
# CHUNKED GENERATION
# ==============================
def call_llm_chunked(
    system_prompt: str,
    generation_plan: List[str],
) -> List[str]:
    """
    Генерация длинного юридического документа по частям.
    """

    results: List[str] = []
    context_so_far = ""

    for step in generation_plan:
        print(f"Генерация: {step}")

        messages = [
            {"role": "system", "content": system_prompt},
            {
                "role": "user",
                "content": f"""
Сформируй следующую часть документа: {step}.

Учитывай ранее сгенерированный текст.
Избегай повторов.
Сохраняй логическую и юридическую последовательность.

Ранее сформированный текст:
{context_so_far}
""".strip(),
            },
        ]

        response = _client.chat.completions.create(
            model=MODEL,
            messages=messages,
            temperature=0.2,
        )

        part_text = response.choices[0].message.content.strip()
        results.append(part_text)
        context_so_far += "\n\n" + part_text

    return results

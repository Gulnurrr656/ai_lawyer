# =========================

def resolve_addressee(doc_kind: DocKind, text: str) -> Addressee:
    """
    Определяет адресата по типу документа и смыслу текста.
    Возвращает Addressee, который можно прямо добавить в facts.
    """

    t = (text or "").lower()

    # 1) Если это иск — суд всегда
    if doc_kind == "lawsuit":
        return Addressee(
            target_type="court",
            target_name="Суд Республики Казахстан (по подсудности)",
            target_note=(
                "Адресат определяется по правилам подсудности (место нахождения ответчика / "
                "место исполнения обязательства). На следующем шаге можно рассчитать подсудность и госпошлину."
            ),
            expected_attachments=(
                "Доказательства, копии документов, расчёт суммы, квитанция госпошлины (если применимо), "
                "копии для сторон."
            ),
        )

    # 2) Жалобы: госорганы (по ключевым словам)
    if doc_kind == "complaint":
        # приоритет — полиция если есть криминальные слова
        if _has_any(t, KW["police"]):
            return Addressee(
                target_type="police",
                target_name="Органы полиции (ДП/УП по месту события)",
                target_note="По тексту просматриваются признаки правонарушения/преступления — обращение в полицию.",
                expected_attachments="Аудио/видео, переписка, чеки, договоры, контакты свидетелей, мед.справки (если есть).",
            )
        if _has_any(t, KW["tax"]):
            return Addressee(
                target_type="tax",
                target_name="Органы государственных доходов (КГД) по месту регистрации",
                target_note="По тексту предмет связан с налогами/ЭСФ/НДС — корректный адресат: КГД.",
                expected_attachments="ЭСФ, договора, акты, выписки, переписка, расчёты, уведомления КГД (если есть).",
            )
        if _has_any(t, KW["consumer_protection"]):
            return Addressee(
                target_type="consumer_protection",
                target_name="Уполномоченный орган по защите прав потребителей",
                target_note="По тексту спор как у потребителя с продавцом/исполнителем услуг.",
                expected_attachments="Чек/оплата, заказ/накладная, переписка, фото/видео недостатков, гарантийные талоны.",
            )
        if _has_any(t, KW["labor_inspection"]):
            return Addressee(
                target_type="labor_inspection",
                target_name="Государственная инспекция труда (по региону)",
                target_note="По тексту просматривается трудовой спор — жалоба в трудовую инспекцию.",
                expected_attachments="Трудовой договор, приказы, табели/графики, расчетные листки, переписка, банковские выписки.",
            )
        if _has_any(t, KW["bailiff"]):
            return Addressee(
                target_type="bailiff",
                target_name="Судебный исполнитель (ЧСИ/ГСИ) / орган юстиции по месту ИП",
                target_note="По тексту речь об исполнительном производстве — жалоба на действия/бездействие судебного исполнителя.",
                expected_attachments="Постановления ЧСИ/ГСИ, материалы ИП, запросы/ответы, доказательства нарушений сроков/процедуры.",
            )
        if _has_any(t, KW["antimonopoly"]):
            return Addressee(
                target_type="antimonopoly",
                target_name="Антимонопольный орган (АЗРК) / департамент по региону",
                target_note="По тексту признаки антиконкурентных действий/монополии — адресат: АЗРК.",
                expected_attachments="Договоры/прайсы/переписка, данные о рынке/ценах, доказательства навязывания условий.",
            )
        if _has_any(t, KW["financial_regulator"]):
            return Addressee(
                target_type="financial_regulator",
                target_name="Финансовый регулятор (АРРФР / Нацбанк — по компетенции)",
                target_note="По тексту финансовая организация (банк/МФО/коллектор) — обращение в регулятор.",
                expected_attachments="Договор займа/кредита, график платежей, выписки, переписка, уведомления/требования, записи звонков (если есть).",
            )
        if _has_any(t, KW["akimat"]):
            return Addressee(
                target_type="akimat",
                target_name="Акимат / профильное управление (по региону)",
                target_note="По тексту спор/вопрос относится к сфере компетенции местного исполнительного органа.",
                expected_attachments="Заявления/ответы госоргана, документы на объект/землю, фото, переписка, квитанции.",
            )
        if _has_any(t, KW["prosecutor"]):
            return Addressee(
                target_type="prosecutor",
                target_name="Прокуратура (по месту нарушения)",
                target_note="По тексту есть признаки надзорного реагирования — возможна подача в прокуратуру.",
                expected_attachments="Доказательства, переписка, ответы госорганов/компаний, копии документов, список нарушенных прав.",
            )

        # дефолтная жалоба — прокуратура как универсальный надзорный вариант
        return Addressee(
            target_type="other_state_body",
            target_name="Уполномоченный государственный орган (по компетенции)",
            target_note=(
                "Точный адресат зависит от предмета (налоги/полиция/акимат/инспекция и т.д.). "
                "Если сомневаемся — можно сформировать универсальную жалобу и предложить варианты адресата."
            ),
            expected_attachments="Документы и доказательства по ситуации: переписка, чеки/платежи, договоры, фото/видео, ответы органов (если есть).",
        )

    # 3) Претензия — всегда контрагенту
    if doc_kind == "claim":
        return Addressee(
            target_type="company",
            target_name="Контрагент (компания/ИП), нарушивший ваши права",
            target_note=(
                "Досудебная претензия направляется нарушителю (по юр.адресу/почте/ЭЦП/электронно, если это предусмотрено). "
                "Можно указать срок ответа и последствия (обращение в суд/госорган)."
            ),
            expected_attachments="Договор/заказ, акты, счета, чеки/платежи, переписка, фото/видео, расчёт требований.",
        )

    # 4) Заявление — чаще в госорган/компанию (по смыслу); дадим нейтрально
    if doc_kind == "statement":
        return Addressee(
            target_type="other_state_body",
            target_name="Адресат по предмету заявления (госорган/организация)",
            target_note="Адресат зависит от того, что именно вы просите (выдать/принять/рассмотреть/предоставить).",
            expected_attachments="Документы, подтверждающие право на обращение и факты (копии удостоверения/договоров/справок по необходимости).",
        )

    # 5) Для договора/консультации адресат не нужен
    return Addressee(
        target_type="company",
        target_name="(Адресат не требуется)",
        target_note="Для договора/консультации адресат не обязателен.",
        expected_attachments="(не применимо)",
    )


def _has_any(text: str, keywords: list[str]) -> bool:
    return any(k in text for k in keywords)

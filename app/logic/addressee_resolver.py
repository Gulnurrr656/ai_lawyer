from __future__ import annotations

from dataclasses import dataclass
from typing import Optional, Literal, Dict

DocKind = Literal["contract", "claim", "complaint", "lawsuit", "statement", "consult"]

TargetType = Literal[
    "company",                 # компания/ИП/контрагент
    "prosecutor",              # прокуратура
    "police",                  # полиция
    "court",                   # суд
    "akimat",                  # акимат
    "tax",                     # налоговые органы / КГД
    "consumer_protection",     # защита прав потребителей
    "labor_inspection",        # трудовая инспекция
    "bailiff",                 # судебный исполнитель
    "antimonopoly",            # АЗРК / антимонопольный орган
    "financial_regulator",     # АРРФР / Нацбанк (финрегулятор)
    "other_state_body",        # прочий госорган
]

@dataclass(frozen=True)
class Addressee:
    target_type: TargetType
    target_name: str
    target_note: str  # пояснение: куда подать / почему это сюда
    expected_attachments: str  # подсказка по приложениям

    def as_facts(self) -> Dict[str, str]:
        return {
            "addressee_target_type": self.target_type,
            "addressee_name": self.target_name,
            "addressee_note": self.target_note,
            "expected_attachments": self.expected_attachments,
        }


